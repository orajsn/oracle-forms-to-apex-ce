#!/usr/bin/env python3
"""Prepare two synthetic, readable FOX journey fixtures without remote actions.

Run with the FOX Python environment and a nonexistent output directory:
    python qa/prepare-fox-journey.py --output work/fox-journey-fixtures-v1

The helper uses the real local extractor. It does not run Oracle tooling, SQL,
models, uploads, or a browser. A setup receipt is published only after both
prepared sets pass integrity checks and their expected native assessments.
The receipt is portable metadata, not source-processing or upload approval.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


# This QA helper lives alongside, rather than inside, the FOX Python package.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "fox"))

from fox.extractor import assert_local_path, prepare, verify  # noqa: E402
from fox.intake import checked_source  # noqa: E402
from fox.native_source import assess_native_source  # noqa: E402
from fox.prepared_source import (  # noqa: E402
    UPLOAD_MANIFEST_NAME,
    encode_upload_manifest,
    verify_upload_manifest,
)


RECEIPT_NAME = "journey-fixtures.json"
TABLE_NAME = "FOX_NATIVE_MINI"
DDL = """CREATE TABLE FOX_NATIVE_MINI (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(1) NOT NULL
);
"""
FORM = """<Module xmlns="http://xmlns.oracle.com/Forms">
  <FormModule Name="MINI">
    <Block Name="MINI" QueryDataSourceName="FOX_NATIVE_MINI" QueryDataSourceType="Table">
      <Item Name="ID"/>
      <Item Name="CODE" Prompt="Code" Required="true"/>
    </Block>
  </FormModule>
</Module>
"""
TRIGGER = '    <Trigger Name="WHEN-NEW-FORM-INSTANCE" TriggerText="BEGIN NULL; END;"/>\n'
EXPECTED_NATIVE_FORM = {
    "profile_id": "native-table-form-v1",
    "data_mode": "synthetic_test_only",
    "table_name": TABLE_NAME,
    "columns": [
        {"name": "ID", "data_type": "NUMBER", "nullable": False,
         "label": "ID", "primary_key": True, "identity": True},
        {"name": "CODE", "data_type": "VARCHAR2", "nullable": False,
         "label": "Code", "primary_key": False, "identity": False, "length": 1},
    ],
    "supported_operations": ["query", "insert", "update"],
}


class FixtureError(ValueError):
    """A bounded, source-free diagnostic suitable for local CLI output."""


def _require(condition: bool, message: str) -> None:
    # Do not use assert: checks must remain active under python -O.
    if not condition:
        raise FixtureError(message)


def _sources(blocked: bool) -> dict[str, bytes]:
    stem = "blocked" if blocked else "mini"
    form = FORM.replace("  </FormModule>", TRIGGER + "  </FormModule>") if blocked else FORM
    return {f"{stem}.xml": form.encode("utf-8"), f"{stem}.sql": DDL.encode("utf-8")}


def _prepare_case(output: Path, case: str) -> dict:
    blocked = case == "blocked"
    originals = _sources(blocked)
    source = output / case / "input"
    source.mkdir(parents=True, exist_ok=False)
    for name, raw in originals.items():
        with (source / name).open("xb") as handle:
            handle.write(raw)

    job_id = f"journey-{case}-v1"
    job = prepare(source, output / case / "extraction", job_id=job_id)
    verified = verify(job)
    _require(verified["status"] == "VERIFIED_REVIEW_REQUIRED"
             and verified["files"] == 2 and verified["approved_for_upload"] is False,
             "The prepared fixture did not pass local integrity verification.")
    ready = job / "ready"
    _require({path.name for path in ready.iterdir()} == {*originals, UPLOAD_MANIFEST_NAME},
             "The ready directory does not contain exactly the intended fixture set.")
    accepted = []
    for name in sorted(originals):
        raw = (ready / name).read_bytes()
        _require(raw == originals[name] == (source / name).read_bytes(),
                 "Fixture source bytes changed during preparation.")
        accepted.append(checked_source(name, raw))

    public_raw = (ready / UPLOAD_MANIFEST_NAME).read_bytes()
    public = verify_upload_manifest(public_raw, accepted)
    _require(public["extraction_job_id"] == job_id
             and encode_upload_manifest(public) == public_raw,
             "The public manifest is not the expected canonical prepared manifest.")
    native = assess_native_source(accepted)
    _require(native["native_form"] == EXPECTED_NATIVE_FORM,
             "The fixture does not match the bounded synthetic native table profile.")
    if blocked:
        expected = {"BUSINESS_CODE_REVIEW_REQUIRED"}
        _require(native["state"] == "BLOCKED"
                 and {item["code"] for item in native["blockers"]} == expected
                 and {item["code"] for item in native["unsupported"]} == expected
                 and len(native["blockers"]) == len(native["unsupported"]) == 1
                 and native["blockers"][0].get("evidence") == "trigger:WHEN-NEW-FORM-INSTANCE"
                 and native["blockers"][0].get("source") == "blocked.xml"
                 and native["unsupported"][0].get("status") == "UNCONVERTED_REVIEW_REQUIRED",
                 "The unsupported-trigger fixture is not blocked for its intended reason.")
    else:
        _require(native["state"] == "READY" and not native["blockers"] and not native["unsupported"],
                 "The happy fixture is not native-profile READY.")

    relative_ready = ready.relative_to(output).as_posix()
    _require(relative_ready == f"{case}/extraction/{job_id}/ready",
             "The prepared fixture path is not the expected portable relative path.")
    return {
        "job_id": job_id,
        "ready_directory": relative_ready,
        "readable_source_hash": public["readable_source_hash"],
        "manifest_sha256": hashlib.sha256(public_raw).hexdigest(),
        "files": public["files"],
    }


def prepare_fixtures(output: Path) -> dict:
    """Create a fresh fixture tree; retain partial output on a failed check.

    An existing directory (including an empty one), file, link or junction is
    never reused. No receipt is emitted for an incomplete preparation.
    """
    output = assert_local_path(output)
    try:
        output.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        raise FixtureError("Output already exists. Choose a new fixture directory.") from None
    receipt = {
        "schema_version": 1,
        "scope": "fox-prepared-journey-fixtures-v1",
        "table_name": TABLE_NAME,
        "happy": _prepare_case(output, "happy"),
        "blocked": _prepare_case(output, "blocked"),
    }
    with (output / RECEIPT_NAME).open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(receipt, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")
    return receipt


def main(argv: list[str] | None = None) -> int:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--output", type=Path, required=True,
                     help="New local directory; must not already exist.")
    args = cli.parse_args(argv)
    try:
        receipt = prepare_fixtures(args.output)
    except FixtureError as exc:
        print(f"Fixture preparation blocked: {exc}", file=sys.stderr)
        return 1
    except (ValueError, OSError, KeyError, TypeError):
        # Never echo arbitrary source content, private manifests or local paths.
        print("Fixture preparation failed. Inspect the local fixture tree; do not use it without a setup receipt.",
              file=sys.stderr)
        return 1
    print(json.dumps(receipt, indent=2, sort_keys=True, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
