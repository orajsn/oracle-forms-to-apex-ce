function changed(mutate,name='ordinary') {
  const original=byName.get(name),project=JSON.parse(original.project_raw),trace=JSON.parse(original.trace_raw);
  mutate(project,trace);
  trace.rendering_spec_sha256=hash(project);
  return {project_raw:JSON.stringify(project),trace_raw:JSON.stringify(trace)};
}

