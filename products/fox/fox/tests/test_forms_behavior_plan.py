def test_control_decoder_receipt_and_line_comment_termination():
    raw = "-- comment&#10;BEGIN&#x9;NULL;&#13;END;"
    text, receipt = decode_control_entities(raw)
    assert text == "-- comment\nBEGIN\tNULL;\rEND;"
    assert [row["codepoint"] for row in receipt["substitutions"]] == [10, 9, 13]
    assert receipt["raw_sha256"] == hashlib.sha256(raw.encode()).hexdigest()
    assert receipt["semantic_sha256"] == hashlib.sha256(text.encode()).hexdigest()
    assert receipt["substitutions"][1]["semantic_character_offset"] == text.index("\t")


