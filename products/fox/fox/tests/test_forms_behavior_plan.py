TRIGGER = """DECLARE unused_value NUMBER;
BEGIN
  -- source comment may describe COMMIT without executing it
  IF NVL(:MASS,0) = 0 THEN
    MESSAGE('Actual amount is required');
    MESSAGE('Actual amount is required');
    RAISE FORM_TRIGGER_FAILURE;
  END IF;
  GO_ITEM('STATE');
END;"""


def documents(trigger=TRIGGER, formula="CEIL(:MASS)", minimum="1", number_type="Number"):
    def attr(value):
        return escape(value.replace("\n", "&#10;"), quote=True)
    xml = (f'<FormModule Name="EXAMPLE"><Block Name="PARCEL" DatabaseBlock="true">'
           f'<Item Name="MASS" DataType="{number_type}" ItemType="Text Item" DatabaseItem="true" '
           f'LowestAllowedValue="{minimum}"><Trigger Name="KEY-NEXT-ITEM" TriggerText="{attr(trigger)}"/></Item>'
           f'<Item Name="STATE" DataType="Char" ItemType="Text Item" DatabaseItem="true"/>'
           f'<Item Name="ROUNDED" DataType="Number" ItemType="Display Item" DatabaseItem="false" Formula="{attr(formula)}"/>'
           '<Trigger Name="OTHER" TriggerText="NULL;"/></Block></FormModule>')
    return [("example.xml", xml.encode())]


def package(docs, mutate=None):
    packet, chunks = _build(docs)
    facts = packet["sources"][0]["facts"]
    block = facts["blocks"][0]
    fields = [{"source_item_id": item["id"], "source_name": item["name"],
               "column": "C_" + item["name"], "data_type": "VARCHAR2" if item["name"] == "STATE" else "NUMBER",
               "report_page_id": 3} for item in facts["items"]]
    trace = {"source_binding": packet["source_binding"], "blocks": [{
        "source_block_id": block["id"], "name": block["name"], "classification": "database",
        "table_name": "FOX_TEST", "report_file": "pages/p00003-parcel.apx", "report_page_id": 3,
        "synthetic_key": {"column": "FOX_ROW_ID", "source_derived": False, "source_item_id": None},
        "items": fields}]}
    manifest = {"source_binding": packet["source_binding"],
                "files": [{key: packet["sources"][0]["source"][key] for key in ("name", "sha256", "bytes")}],
                "selected_chunk_hashes": {c["id"]: c["sha256"] for c in chunks}}
    members = {"fox-package/source-manifest.json": manifest, "fox-package/source-to-page.json": trace,
               "fox-package/supporting-schema.sql": "CREATE TABLE FOX_TEST (\n FOX_ROW_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,\n C_MASS NUMBER,\n C_STATE VARCHAR2(30),\n C_ROUNDED NUMBER\n);\n",
               "pages/p00003-parcel.apx": "page 3 ( region records ( type: interactiveReport source { type: tableView tableName: FOX_TEST } column FOX_ROW_ID ( ) column C_MASS ( ) column C_STATE ( ) column C_ROUNDED ( ) ) )"}
    if mutate:
        mutate(members)
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        for name, content in members.items():
            archive.writestr(name, json.dumps(content) if isinstance(content, dict) else content)
    return output.getvalue()


def test_exact_whole_source_units_bind_without_mutation_or_runtime_claims():
    docs = documents()
    parent = package(docs)
    before = deepcopy(docs), parent
    result = build_behavior_plan(docs, parent)
    assert [op["kind"] for op in result["operations"]] == ["numeric_nonzero_then_focus", "ceil_report_column"]
    validation, formula = result["operations"]
    assert validation["minimum"] == "1"
    assert validation["message_call_count"] == 2
    assert validation["target"]["value_data_type"] == "NUMBER"
    assert validation["target"]["focus_data_type"] == "VARCHAR2"
    assert formula["target"]["input_column"] == "C_MASS"
    assert formula["target"]["output_column"] == "C_ROUNDED"
    assert len(result["coverage"]) == result["code_unit_count"] == 3
    assert sum(row["status"] == "planned_wired_adapted" for row in result["coverage"]) == 2
    assert all(result[key] is False for key in ("native_generated", "runtime_verified", "business_accepted"))
    assert all("source_chunk_id" in row for row in result["coverage"])
    assert validation["decode_receipt"]["substitutions"]
    assert (docs, parent) == before
    assert result == build_behavior_plan(docs, parent)
    unsigned = {key: value for key, value in result.items() if key != "plan_sha256"}
    assert result["plan_sha256"] == hashlib.sha256(json.dumps(unsigned, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


@pytest.mark.parametrize("trigger", [
    TRIGGER + " COMMIT;", "COMMIT; " + TRIGGER,
    TRIGGER.replace("GO_ITEM('STATE');", "COMMIT; GO_ITEM('STATE');"),
    TRIGGER.replace("RAISE FORM_TRIGGER_FAILURE;", "NULL;"),
    TRIGGER.replace("RAISE FORM_TRIGGER_FAILURE;", "MESSAGE('Actual amount is required'); RAISE FORM_TRIGGER_FAILURE;"),
    TRIGGER.replace("MESSAGE('Actual amount is required');", "MESSAGE('Other message');", 1),
    TRIGGER.replace(":MASS", ":OTHER.MASS"),
    TRIGGER.replace("GO_ITEM('STATE')", "GO_ITEM('OTHER.STATE')"),
    TRIGGER.replace("GO_ITEM('STATE')", "GO_ITEM('MASS')"),
    TRIGGER.replace("unused_value NUMBER;", "unused_value NUMBER := 0;"),
    TRIGGER.replace("Actual amount is required", "Value &#10; is encoded"),
    TRIGGER.replace("Actual amount is required", "Value &P1_NAME. is unsafe"),
    TRIGGER.replace("Actual amount is required", "<b>required</b>"),
    TRIGGER.replace("GO_ITEM('STATE');", "OTHER_API.RUN; GO_ITEM('STATE');"),
])
def test_extra_active_logic_or_ambiguous_literals_never_partially_convert(trigger):
    docs = documents(trigger=trigger)
    result = build_behavior_plan(docs, package(docs))
    assert [op["kind"] for op in result["operations"]] == ["ceil_report_column"]
    assert result["coverage"][0]["status"] == "unsupported"


