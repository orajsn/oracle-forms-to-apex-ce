def test_parent_missing_source_selection_is_not_generated_or_silently_dropped():
    docs = documents()
    result = build_behavior_plan(docs, package(docs, lambda members: members["fox-package/source-manifest.json"].update(selected_chunk_hashes={})))
    assert result["operations"] == []
    assert len(result["coverage"]) == 3
    assert sum(row["status"] == "missing_input" for row in result["coverage"]) == 2


def test_explicit_selection_is_complete_unique_and_does_not_drop_other_coverage():
    docs = documents()
    parent = package(docs)
    all_plan = build_behavior_plan(docs, parent)
    selected = all_plan["operations"][1]["source_unit_id"]
    result = build_behavior_plan(docs, parent, [selected])
    assert len(result["operations"]) == 1
    assert len(result["coverage"]) == 3
    assert build_behavior_plan(docs, parent, [])["operations"] == []
    for invalid in ([selected, selected], ["unknown"], selected, [None]):
        with pytest.raises(ValueError):
            build_behavior_plan(docs, parent, invalid)


