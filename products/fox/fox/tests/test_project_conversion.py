def ddl(table="FOX_NATIVE_ALPHA", kind="VARCHAR2(40)", nullable="NOT NULL"):
    return f"CREATE TABLE {table} (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE {kind} {nullable});"


def module(name="ALPHA", table="FOX_NATIVE_ALPHA", prompt="Title", extra=""):
    return (f'<FormModule Name={quoteattr(name)}><Block Name="MAIN" QueryDataSourceName={quoteattr(table)}>'
            f'<Item Name="ID"/><Item Name="TITLE" Prompt={quoteattr(prompt)}/></Block>{extra}</FormModule>')


def xml(*modules):
    return '<Module xmlns="http://xmlns.oracle.com/Forms">' + ''.join(modules) + '</Module>'


def source(name, text, bom=False):
    raw = (b'\xef\xbb\xbf' if bom else b'') + text.encode()
    return checked_source(name, raw)


def pair(name="ALPHA", table="FOX_NATIVE_ALPHA", prompt="Title"):
    return [source(name.lower() + ".xml", xml(module(name, table, prompt))), source(name.lower() + ".sql", ddl(table))]


def assess(files, project_id="project-one", project_name="Example project"):
    return assess_project_conversion(files, project_id=project_id, project_name=project_name,
                                     source_hash=inventory(files)["source_hash"])


def findings(plan):
    return plan["project_findings"] + [item for form in plan["forms"] for item in form["findings"]]


def codes(plan):
    return {item["code"] for item in findings(plan)}


