"""Mapped-source QA plans use the actual source planner and project renderer.

Runtime observations remain authored unit-test records, not live APEX proof.
The durable proof suite separately exercises real generated project packages.
"""
from copy import deepcopy
from pathlib import Path

import pytest

from fox.intake import checked_source, inventory
from fox.project_conversion import assess_project_conversion
from fox.project_qa_plan import ProjectQaPlanError, derive_project_qa_profile, validate_project_qa_result
from fox.native_qa_plan import qa_plan_sha256
from test_project_qa_plan import objects, plan_for, runtime


@pytest.fixture
def mapped(monkeypatch):
    monkeypatch.syspath_prepend(str(Path(__file__).resolve().parents[2] / "converter"))
    from forms2apex.native_project import project_trace
    files = [checked_source(name.lower() + ".xml", (
        f'<FormModule Name="{name}"><Block Name="MAIN" QueryDataSourceName="WORK_ITEMS">'
        '<Item Name="ID"/><Item Name="TITLE" Prompt="Title"/></Block></FormModule>').encode())
        for name in ("ALPHA", "BETA")]
    files += [checked_source("work-items.sql", b"CREATE TABLE WORK_ITEMS (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(20) NOT NULL);")]
    assessment = assess_project_conversion(files, project_id="qa-mapped-project", project_name="Synthetic mapped QA",
                                           source_hash=inventory(files)["source_hash"])
    assert assessment["state"] == "READY"
    project = assessment["rendering_spec"]
    assert project["schema_version"] == 2
    return project, project_trace(project)


def test_mapped_plan_recomputes_mapping_but_keeps_physical_runtime_format(mapped):
    project, trace = mapped
    before = deepcopy(mapped)
    plan = plan_for(project, trace)
    assert mapped == before
    assert plan["schema_version"] == 1 and plan["scope"] == "fox-project-qa-plan-v1"
    assert plan["project_spec_sha256"] == qa_plan_sha256(project)
    assert plan["source_to_apex_sha256"] == qa_plan_sha256(trace)
    assert len(plan["tables"]) == 1 and len(plan["forms"]) == 2
    physical = project["forms"][0]["storage_mapping"]["target_table_name"]
    assert plan["tables"][0]["table_name"] == physical and physical != "WORK_ITEMS"
    assert set(plan["tables"][0]) == {"table_name", "schema_contract_sha256", "module_ids"}
    assert all(form["table_name"] == physical for form in plan["forms"])
    assert derive_project_qa_profile(project, plan)["schema_version"] == 1
    assert len(validate_project_qa_result(runtime(project, plan), project, plan, 444)) == 2


@pytest.mark.parametrize("change", [
    lambda p, t: p.update(schema_version=1),
    lambda p, t: p.update(project_id="another-project"),
    lambda p, t: p.update(unknown=True),
    lambda p, t: p["forms"][0].pop("storage_mapping"),
    lambda p, t: p["forms"][0].pop("ddl_sources"),
    lambda p, t: p["forms"][0]["storage_mapping"].update(schema_version=True),
    lambda p, t: p["forms"][0]["storage_mapping"].update(source_table_name="OTHER_TABLE"),
    lambda p, t: p["forms"][0]["storage_mapping"].update(source_schema_sha256="a" * 64),
    lambda p, t: p["forms"][0]["storage_mapping"].update(identity_sha256="b" * 64),
    lambda p, t: p["forms"][0]["storage_mapping"].update(target_table_name="FOX_NATIVE_OTHER"),
    lambda p, t: p["forms"][0]["native_form"].update(table_name="WORK_ITEMS"),
    lambda p, t: p["forms"][0]["native_form"]["columns"][1].update(length=21),
    lambda p, t: p["forms"][0]["native_form"]["columns"][1].pop("identity"),
    lambda p, t: p["forms"][0]["ddl_sources"].append(deepcopy(p["forms"][0]["ddl_sources"][0])),
    lambda p, t: p["forms"][1]["ddl_sources"][0].update(sha256="c" * 64),
    lambda p, t: p["forms"][0]["ddl_sources"][0].update(name="../original.sql"),
    lambda p, t: t.update(schema_version=1, scope="fox-native-project-render-trace-v1"),
    lambda p, t: t.update(project_id="another-project"),
    lambda p, t: t.update(unknown=True),
    lambda p, t: t["forms"][0].pop("storage_mapping"),
    lambda p, t: t["forms"][0]["ddl_sources"][0].update(sha256="d" * 64),
    lambda p, t: t["tables"][0].pop("ddl_sources"),
    lambda p, t: t["tables"][0]["storage_mapping"].update(identity_sha256="e" * 64),
    lambda p, t: t["tables"][0]["ddl_sources"].append(deepcopy(t["tables"][0]["ddl_sources"][0])),
])
def test_mapped_contract_rejects_forged_schema_mapping_or_source_reference(mapped, change):
    project, trace = deepcopy(mapped)
    change(project, trace)
    # Rebinding the outer spec hash must not hide a forged inner identity.
    trace["rendering_spec_sha256"] = qa_plan_sha256(project)
    with pytest.raises(ProjectQaPlanError):
        plan_for(project, trace)


@pytest.mark.parametrize("change", [
    lambda p, t: p.update(project_id="unexpected"),
    lambda p, t: p["forms"][0].update(ddl_sources=[]),
    lambda p, t: t.update(project_id="unexpected"),
    lambda p, t: t.update(unknown=True),
    lambda p, t: t["forms"][0].update(storage_mapping={}),
    lambda p, t: t["tables"][0].update(ddl_sources=[]),
])
def test_v1_does_not_silently_accept_v2_or_unknown_fields(change):
    project, trace = objects()
    change(project, trace)
    trace["rendering_spec_sha256"] = qa_plan_sha256(project)
    with pytest.raises(ProjectQaPlanError):
        plan_for(project, trace)
