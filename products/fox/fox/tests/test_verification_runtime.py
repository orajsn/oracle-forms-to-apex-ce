def test_two_concurrent_managed_projects_get_exactly_one_admission(tmp_path, monkeypatch):
    with app_client(tmp_path, monkeypatch) as (client, root):
        configure_native_admission(monkeypatch); login_admission(client)
        projects = [ready_project(client, f'Concurrent synthetic project {index}') for index in range(2)]
        barrier = Barrier(2)
        def submit(item):
            project, body = item
            barrier.wait(timeout=10)
            return project, client.post(f'/api/projects/{project}/runs', json=body)
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(submit, projects))
        assert sorted(response.status_code for _, response in results) == [202, 429]
        rejected_project = next(project for project, response in results if response.status_code == 429)
        saved = client.get(f'/api/projects/{rejected_project}').json()
        assert saved['runs'] == [] and len(saved['inventory']['files']) == 2
        with closing(sqlite3.connect(root / 'fox.sqlite3')) as db:
            assert db.execute('SELECT COUNT(*) FROM runs').fetchone()[0] == 1
            assert db.execute("SELECT COUNT(*) FROM events WHERE action='approved_conversion'").fetchone()[0] == 1
        assert len(list((root / 'jobs').iterdir())) == 1
