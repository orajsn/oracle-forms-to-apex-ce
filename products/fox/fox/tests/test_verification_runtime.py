@pytest.mark.parametrize('failure_mode', ['none', 'enqueue', 'enqueue_and_diagnostic'])
def test_worker_hands_off_completed_native_package_without_reconversion(tmp_path, monkeypatch, failure_mode):
    case = seed(tmp_path / 'worker', state='QUEUED')
    runtime.initialize(case.root)
    handoff_fails = failure_mode != 'none'
    if failure_mode == 'enqueue_and_diagnostic':
        with closing(sqlite3.connect(case.root / 'fox.sqlite3')) as db, db:
            db.execute("CREATE TRIGGER fail_handoff_diagnostic BEFORE UPDATE OF message ON runs "
                       "WHEN OLD.state='QA_REQUIRED' AND NEW.state='QA_REQUIRED' "
                       "BEGIN SELECT RAISE(ABORT,'synthetic diagnostic storage failure'); END")
    before = {path: path.read_bytes() for path in case.job.rglob('*') if path.is_file()}
    monkeypatch.setattr(socket.socket, 'connect', forbidden)
    monkeypatch.setenv('FOX_RUN_ADAPTER', 'synthetic-local-adapter')
    calls = []
    def adapter(args, **kwargs):
        assert args == ['synthetic-local-adapter', str(case.job)]
        calls.append(args)
        return SimpleNamespace(returncode=0)
    monkeypatch.setattr(worker.subprocess, 'run', adapter)
    if handoff_fails:
        def failed(*args, **kwargs): raise RuntimeError(SECRET)
        monkeypatch.setattr(runtime, 'enqueue_native', failed)
    def db():
        value = sqlite3.connect(case.root / 'fox.sqlite3')
        value.row_factory = sqlite3.Row
        return value
    worker.process_one(db, case.root)
    worker.process_one(db, case.root)
    with closing(db()) as connection:
        row = connection.execute('SELECT * FROM runs WHERE id=?', (JOB,)).fetchone()
    assert row['state'] == 'QA_REQUIRED'
    assert row['artifact'] == str((case.job / 'apex-package.zip').relative_to(case.root))
    assert len(calls) == 1 and SECRET not in row['message']
    assert {path: path.read_bytes() for path in before} == before
    queued = runtime.configured_queue(case.root).get(JOB)
    assert (queued is None) is handoff_fails
    if failure_mode == 'enqueue':
        assert 'retained' in row['message'] and 'do not restart conversion' in row['message']
    elif failure_mode == 'enqueue_and_diagnostic':
        assert row['message'].startswith('Technical checks passed.')
        assert runtime.public_status(case.root, {**case.run, 'state': 'QA_REQUIRED'})['state'] == 'not_queued'
    else:
        assert queued['state'] == 'queued' and queued['package_sha256'] == sha(case.package)
    assert table_rows(case.root, 'acceptances') == table_rows(case.root, 'events') == []


