    monkeypatch.setenv('FOX_DATA_DIR', str(root))
    monkeypatch.setenv('FOX_VERIFICATION_ENABLED', '1' if enabled else '0')
    monkeypatch.setenv('FOX_VERIFIER_RELEASE_SHA256', RELEASE)
    monkeypatch.setenv('FOX_ADMIN_USERNAME', OWNER)
    monkeypatch.setenv('FOX_PUBLIC_ORIGIN', ORIGIN)
    from fastapi.testclient import TestClient
    from fox.app import create_app, password_hash
    monkeypatch.setenv('FOX_PASSWORD_HASH', password_hash('synthetic-runtime-test-only'))
    with TestClient(create_app(root, enable_worker=False), base_url=ORIGIN) as client:
        # Allow only Windows asyncio's initial local self-pipe setup, then guard
        # all product requests against opening sockets.
        monkeypatch.setattr(socket.socket, 'connect', forbidden)
        client.headers['Origin'] = ORIGIN
        yield client, root


