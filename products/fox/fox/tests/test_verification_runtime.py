@pytest.mark.parametrize('mutation', ['malformed_snapshot', 'malformed_release', 'malformed_download',
    'source_text', 'source_hash', 'source_bytes', 'source_manifest', 'duplicate_source', 'empty_sources',
    'wrong_profile', 'wrong_job', 'wrong_release_source', 'download_package', 'download_source', 'download_extra', 'changed_package'])
def test_malformed_or_changed_retained_binding_cannot_enqueue(retained, mutation):
    snapshot, release = deepcopy(retained.snapshot), deepcopy(retained.release)
    download = {'source_hash': retained.run['source_hash'], 'package_sha256': sha(retained.package)}
    if mutation == 'source_text': snapshot['files'][0]['text'] += '\n'
    elif mutation == 'source_hash': snapshot['files'][0]['sha256'] = 'f' * 64
    elif mutation == 'source_bytes': snapshot['files'][0]['bytes'] += 3
    elif mutation == 'source_manifest': snapshot['source_hash'] = 'f' * 64
    elif mutation == 'duplicate_source': snapshot['files'].append(deepcopy(snapshot['files'][0]))
    elif mutation == 'empty_sources': snapshot['files'] = []
    elif mutation == 'wrong_profile': snapshot['conversion_profile'] = 'legacy-html-prototype-v1'
    elif mutation == 'wrong_job': release['job_id'] = 'fox-' + 'f' * 20
    elif mutation == 'wrong_release_source': release['source_manifest_sha256'] = 'f' * 64
    elif mutation == 'download_package': download['package_sha256'] = 'f' * 64
    elif mutation == 'download_source': download['source_hash'] = 'f' * 64
    elif mutation == 'download_extra': download['browser_release_override'] = OTHER_RELEASE
    elif mutation == 'changed_package': (retained.job / 'apex-package.zip').write_bytes(b'changed')
    (retained.job / 'source-snapshot.json').write_bytes(b'{' if mutation == 'malformed_snapshot' else raw(snapshot))
    (retained.job / 'release-evidence.json').write_bytes(b'{' if mutation == 'malformed_release' else raw(release))
    (retained.job / 'native-pipeline/download.json').write_bytes(b'{' if mutation == 'malformed_download' else raw(download))
    with pytest.raises(runtime.VerificationRuntimeError):
        runtime.enqueue_native(retained.root, JOB)
    assert table_rows(retained.root, 'verification_queue') == []


