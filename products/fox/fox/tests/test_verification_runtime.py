def seed(root, *, xml=XML, state='QA_REQUIRED', project='synthetic-project'):
    """A retained scheduling fixture, explicitly not an importable APEX proof."""
    root.mkdir(parents=True, exist_ok=True)
    job = root / 'jobs' / JOB
    (job / 'native-pipeline').mkdir(parents=True)
    files = [checked_source('native.xml', xml), checked_source('native.sql', DDL)]
    source_hash = inventory(files)['source_hash']
    package = b'SYNTHETIC retained package bytes: scheduling test only, never executable APEX'
    snapshot = {'project': project, 'source_hash': source_hash, 'conversion_profile': PROFILE,
                'files': files, 'approvals': dict.fromkeys(('redacted_source', 'external_ai', 'synthetic_prototype'), True)}
    release = {'job_id': JOB, 'source_manifest_sha256': source_hash, 'conversion_profile': PROFILE,
               **dict.fromkeys(('reviewer_approved', 'reviewer_execution_verified', 'sqlcl_valid',
                                'import_passed', 'runtime_smoke_passed', 'package_reimport_passed'), True)}
    for name, content in {'source-snapshot.json': raw(snapshot), 'release-evidence.json': raw(release),
                          'apex-package.zip': package,
                          'native-pipeline/download.json': raw({'source_hash': source_hash, 'package_sha256': sha(package)})}.items():
        (job / name).write_bytes(content)
    with closing(sqlite3.connect(root / 'fox.sqlite3')) as db, db:
        db.executescript('''
            CREATE TABLE IF NOT EXISTS runs(id TEXT PRIMARY KEY,project TEXT,source_hash TEXT,state TEXT,
              message TEXT,created REAL,updated REAL,artifact TEXT);
            CREATE TABLE IF NOT EXISTS acceptances(run TEXT,owner TEXT,notes TEXT);
            CREATE TABLE IF NOT EXISTS events(owner TEXT,action TEXT,object_id TEXT,created REAL);
        ''')
        db.execute('INSERT INTO runs VALUES(?,?,?,?,?,?,?,?)', (
            JOB, project, source_hash, state, 'Synthetic retained fixture', 1.0, 1.0,
            str((job / 'apex-package.zip').relative_to(root))))
    return SimpleNamespace(root=root, job=job, snapshot=snapshot, release=release, package=package,
                           run={'id': JOB, 'source_hash': source_hash, 'state': state})


