def test_comments_do_not_join_tokens_or_hide_statements():
    result = assess_native_source(sources(ddl=DDL.replace("CREATE TABLE", "CRE/**/ATE TABLE")))
    assert result["state"] == "BLOCKED"
    result = assess_native_source(sources(ddl=DDL + " /* nothing */ DROP TABLE FOX_NATIVE_BETA;"))
    assert result["state"] == "BLOCKED"


def test_humanized_labels_still_must_pass_native_contract():
    result = assess_native_source(sources(form=FORM.replace("DUE_DATE", "CREATE_TABLE"), ddl=DDL.replace("DUE_DATE", "CREATE_TABLE")))
    assert result["state"] == "BLOCKED" and "LABEL_REVIEW_REQUIRED" in codes(result)
    form = FORM.replace('<Item Name="DUE_DATE"/>', '<Item Name="CREATE_TABLE" Prompt="Due Date"/>')
    assert assess_native_source(sources(form=form, ddl=DDL.replace("DUE_DATE", "CREATE_TABLE")))["state"] == "READY"


def test_sources_not_mutated_and_hashes_recomputed_from_text():
    data = sources()
    data[0]["sha256"] = "untrusted-client-value"
    first = assess_native_source(data)
    second = assess_native_source(list(reversed(data)))
    assert first["native_form"] == second["native_form"]
    assert data[0]["text"] == FORM and data[1]["text"] == DDL
    assert "untrusted-client-value" not in str(first)


