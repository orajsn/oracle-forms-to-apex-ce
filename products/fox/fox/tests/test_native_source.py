@pytest.mark.parametrize("tail", [
    "\nDROP TABLE FOX_NATIVE_BETA;", "\nCOMMIT;", "\n/", "\n@@another.sql", "\nprompt done",
    "\nCREATE TABLE FOX_NATIVE_NEXT (ID NUMBER, TITLE VARCHAR2(100));", "\n/* unfinished",
    "\n/* outer /* nested */ */", "\n;",
])
def test_unparsed_leftovers_scripts_and_second_statements_block(tail):
    result = assess_native_source(sources(ddl=DDL + tail))
    assert result["state"] == "BLOCKED" and result["native_form"] is None
    assert "UNPARSED_DDL" in codes(result)


def test_records_and_business_source_code_are_distinct_blockers():
    records = assess_native_source(sources(ddl=DDL + "\nINSERT INTO FOX_NATIVE_BETA (TITLE) VALUES ('synthetic -- record');"))
    assert records["state"] == "BLOCKED"
    assert "DATA_OR_SCRIPT_SQL" in codes(records)
    form = FORM.replace("</Block>", '<Trigger Name="SAVE" TriggerText="INSERT INTO FOX_NATIVE_BETA (TITLE) VALUES (:BETA.TITLE);"/></Block>')
    code = assess_native_source(sources(form=form))
    assert code["state"] == "BLOCKED" and code["native_form"] is not None
    assert "BUSINESS_CODE_REVIEW_REQUIRED" in codes(code)
    assert "DATA_OR_SCRIPT_SQL" not in codes(code)
    assert any(item["status"] == "UNCONVERTED_REVIEW_REQUIRED" for item in code["unsupported"])


