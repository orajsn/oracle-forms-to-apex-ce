"""All fixtures are synthetic; no customer source is read or uploaded."""
import importlib.util
from pathlib import Path

import pytest

from fox.native_source import assess_native_source


DDL = """CREATE TABLE FOX_NATIVE_BETA (
    ID number generated by default on null as identity primary key,
    TITLE varchar2(100) not null,
    STATUS varchar2(20) not null,
    AMOUNT number not null,
    DUE_DATE date
);"""
FORM = """<Module xmlns="http://xmlns.oracle.com/Forms"><FormModule Name="BETA">
    <Block Name="BETA" QueryDataSourceName="FOX_NATIVE_BETA" QueryDataSourceType="Table">
      <Item Name="ID"/><Item Name="TITLE" Prompt="Work title"/>
      <Item Name="STATUS"/><Item Name="AMOUNT"/><Item Name="DUE_DATE"/>
    </Block></FormModule></Module>"""


def sources(form=FORM, ddl=DDL):
    return [{"name": "beta.xml", "text": form}, {"name": "beta.sql", "text": ddl}]


def codes(result):
    return {item["code"] for item in result["blockers"]}


def test_ready_is_exact_typed_synthetic_contract_and_matches_converter_validator():
    result = assess_native_source(sources())
    assert result["state"] == "READY"
    assert not result["blockers"] and not result["unsupported"]
    native = result["native_form"]
    assert native["table_name"] == "FOX_NATIVE_BETA"
    assert native["data_mode"] == "synthetic_test_only"
    assert native["columns"][0] == {"name": "ID", "data_type": "NUMBER", "nullable": False,
                                     "label": "ID", "primary_key": True, "identity": True}
    assert native["columns"][1]["label"] == "Work title"
    assert native["columns"][1]["length"] == 100
    assert native["columns"][-1]["nullable"] is True
    assert native["columns"][-1]["label"] == "Due Date"
    # FOX and converter deploy separately: import the validator only in this
    # cross-package contract test, never at runtime via a filesystem path.
    validator_path = Path(__file__).resolve().parents[2] / "converter/forms2apex/native_contract.py"
    spec = importlib.util.spec_from_file_location("native_contract_parity", validator_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert module.validate_native_spec(native) == native
    assert {r["kind"] for r in result["source_refs"]} == {"source_file", "forms_table", "table_definition", "column_label"}


