"""Synthetic source-guidance regressions; no Oracle, AI, DB or network calls."""
from copy import deepcopy

import pytest

from fox.intake import checked_source, inventory
from fox.project_conversion import assess_project_conversion


def src(name, text):
    return checked_source(name, text.encode('utf-8'))


def form(code='ORDER_API.APPROVE_ORDER();'):
    # Code in these fixtures never contains XML attribute delimiters.
    return src('orders.xml', '<Module xmlns="http://xmlns.oracle.com/Forms"><FormModule Name="ORDER_ENTRY">'
        '<Block Name="ORDERS" QueryDataSourceName="FOX_NATIVE_ORDERS">'
        '<Item Name="ID"/><Item Name="TITLE"/>'
        '<Item Name="APPROVE" ItemType="Push Button" DatabaseItem="false" Label="Approve order">'
        '<Trigger Name="WHEN-BUTTON-PRESSED" TriggerText="' + code + '"/>'
        '</Item></Block></FormModule></Module>')


def spec(routine='APPROVE_ORDER'):
    return src('order_api.pks', 'CREATE PACKAGE ORDER_API AS PROCEDURE ' + routine + '; END;')


def body(routine='APPROVE_ORDER'):
    return src('order_api.pkb', 'CREATE PACKAGE BODY ORDER_API AS PROCEDURE ' + routine +
               ' IS BEGIN NULL; END; END;')


def ddl():
    return src('orders.sql', 'CREATE TABLE FOX_NATIVE_ORDERS ('
        'ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(40));')


def assess(files):
    return assess_project_conversion(files, project_id='dependency-guidance',
        project_name='Synthetic orders', source_hash=inventory(files)['source_hash'])


def package(result):
    return next(item for item in result['dependencies'] if item['kind'] == 'package')


def test_exact_button_path_and_only_missing_body_are_explained():
    files = [form(), spec()]
    result = package(inventory(files))
    assert result['target'] == 'ORDER_API' and result['routine'] == 'APPROVE_ORDER'
    assert result['source_location'] == {'form': 'ORDER_ENTRY', 'block': 'ORDERS', 'item': 'APPROVE',
        'button': 'Approve order', 'trigger': 'WHEN-BUTTON-PRESSED', 'code_property': 'triggertext', 'code_line': 1}
    assert result['missing_parts'] == ['package_body']
    assert '.pkb' in result['action'] and '.pks' not in result['action']
    assert result['routine_check'] == 'MISSING_SOURCE'


def test_both_missing_parts_have_explicit_formats_without_invented_filenames():
    result = package(inventory([form()]))
    assert result['missing_parts'] == ['package', 'package_body']
    assert '.pks or readable SQL' in result['action'] and '.pkb or readable SQL' in result['action']


def test_adding_body_resolves_availability_but_does_not_claim_converted_behavior():
    files = [form(), ddl(), spec()]
    first = assess(files)
    original = deepcopy(files)
    complete = assess(files + [body()])
    first_codes = {f['code'] for f in first['forms'][0]['findings']}
    later_codes = {f['code'] for f in complete['forms'][0]['findings']}
    assert 'MISSING_DEPENDENCY' in first_codes
    assert 'MISSING_DEPENDENCY' not in later_codes
    dep = package(complete['forms'][0])
    assert dep['status'] == 'SOURCE_PRESENT' and dep['routine_check'] == 'DECLARATIONS_FOUND'
    assert dep['missing_parts'] == [] and 'Behavior still needs' in dep['action']
    assert 'BUSINESS_CODE_REVIEW_REQUIRED' in later_codes
    assert complete['can_generate'] is False and complete['rendering_spec'] is None
    assert first['source_hash'] != complete['source_hash']
    assert files == original


def test_wrong_routine_is_not_a_successful_source_resolution():
    result = assess([form(), ddl(), spec('CANCEL_ORDER'), body('CANCEL_ORDER')])
    dep = package(result['forms'][0])
    assert dep['status'] == 'SOURCE_PRESENT'  # Files really exist, not falsely missing.
    assert dep['routine_check'] == 'NOT_CONFIRMED'
    assert 'ROUTINE_DECLARATION_UNCONFIRMED' in {f['code'] for f in result['forms'][0]['findings']}
    assert not result['can_generate']


def test_finding_retains_source_path_impact_and_next_action():
    result = assess([form(), ddl(), spec()])
    finding = next(item for item in result['forms'][0]['findings'] if item['code'] == 'MISSING_DEPENDENCY')
    assert finding['source_location']['button'] == 'Approve order'
    assert 'cannot reproduce' in finding['impact'] and '.pkb' in finding['required_action']
    assert finding['owner'] == 'SOURCE_OWNER'


def test_calls_from_distinct_buttons_and_routines_are_not_collapsed():
    text = form().get('text').replace('</Block>', '<Item Name="CANCEL" ItemType="Push Button" DatabaseItem="false">'
        '<Trigger Name="WHEN-BUTTON-PRESSED" TriggerText="ORDER_API.CANCEL_ORDER();"/></Item></Block>')
    deps = [d for d in inventory([src('orders.xml', text)])['dependencies'] if d['kind'] == 'package']
    assert [(d['routine'], d['source_location']['item']) for d in deps] == [
        ('APPROVE_ORDER', 'APPROVE'), ('CANCEL_ORDER', 'CANCEL')]


def test_module_trigger_does_not_invent_a_button():
    source = src('startup.xml', '<FormModule Name="STARTUP"><Trigger Name="WHEN-NEW-FORM-INSTANCE" '
        'TriggerText="CUSTOM_API.RUN();"/></FormModule>')
    location = package(inventory([source]))['source_location']
    assert location['form'] == 'STARTUP' and location['trigger'] == 'WHEN-NEW-FORM-INSTANCE'
    assert 'button' not in location and 'item' not in location


@pytest.mark.parametrize('code', [
    "-- FAKE_API.RUN();\nNULL;", "/* FAKE_API.RUN(); */ NULL;",
    "MESSAGE('FAKE_API.RUN();');", "MESSAGE(q'[FAKE_API.RUN();]');",
    "MESSAGE('not -- a comment'); /* FAKE_API.RUN(); */ NULL;",
    "MESSAGE('CALL_FORM(''MISSING_FORM'')');",
])
def test_comments_and_literals_do_not_request_fictitious_dependencies(code):
    source = src('code.sql', code)
    result = inventory([source])
    assert result['dependencies'] == []


def test_actual_literal_module_reference_is_retained():
    source = src('code.sql', "CALL_FORM('ORDER_DETAIL');")
    assert inventory([source])['dependencies'][0]['target'] == 'ORDER_DETAIL'


def test_comment_looking_text_in_a_string_does_not_hide_a_real_call():
    source = src('code.sql', "MESSAGE('not -- a comment');\nREAL_API.RUN();")
    dep = package(inventory([source]))
    assert dep['target'] == 'REAL_API' and dep['line'] == 2


def test_commented_package_declarations_do_not_supply_missing_source():
    fake = src('fake.sql', '-- CREATE PACKAGE ORDER_API AS PROCEDURE APPROVE_ORDER; END;\n'
        '/* CREATE PACKAGE BODY ORDER_API AS PROCEDURE APPROVE_ORDER IS BEGIN NULL; END; END; */')
    dep = package(inventory([form(), fake]))
    assert dep['status'] == 'MISSING' and len(dep['missing_parts']) == 2


def test_schema_qualified_package_call_is_one_dependency_not_two_names():
    dep = package(inventory([form('APP.ORDER_API.APPROVE_ORDER();')]))
    assert dep['target'] == 'APP.ORDER_API' and dep['routine'] == 'APPROVE_ORDER'


@pytest.mark.parametrize('header', ['PACKAGE BODY', 'PACKAGE   BODY', 'PACKAGE\nBODY'])
def test_valid_package_header_whitespace_is_not_a_missing_file(header):
    supplied = src('order_api.pkb', body()['text'].replace('PACKAGE BODY', header))
    result = assess([form(), ddl(), spec(), supplied])
    dep = package(result['forms'][0])
    assert dep['status'] == 'SOURCE_PRESENT' and dep['routine_check'] == 'DECLARATIONS_FOUND'
    assert dep['missing_parts'] == []


def test_supplied_package_with_a_builtin_name_is_not_silently_ignored():
    supplied = [src('ftree.pks', 'CREATE PACKAGE FTREE AS PROCEDURE FIND_TREE_NODE; END;'),
                src('ftree.pkb', 'CREATE PACKAGE BODY FTREE AS PROCEDURE FIND_TREE_NODE IS BEGIN NULL; END; END;')]
    result = inventory([form('FTREE.FIND_TREE_NODE();'), *supplied])
    dep = package(result)
    assert dep['target'] == 'FTREE' and dep['status'] == 'SOURCE_PRESENT'
    assert dep['routine_check'] == 'DECLARATIONS_FOUND'
    assert not any(item['target'] == 'FTREE.FIND_TREE_NODE' for item in result['issues'])


@pytest.mark.parametrize('member', ['FIND_TREE_NODE', 'ADD_TREE_NODE', 'UNKNOWN_FUTURE_MEMBER'])
def test_oracle_ftree_is_not_a_fictitious_custom_package_upload(member):
    result = inventory([form('FTREE.' + member + '();')])
    assert not any(d['target'] == 'FTREE' for d in result['dependencies'])
    finding = next(item for item in result['issues'] if item['target'] == 'FTREE.' + member)
    assert finding['status'] == 'UNCONVERTED_REVIEW_REQUIRED'
    if member == 'UNKNOWN_FUTURE_MEMBER': assert 'confirmation' in finding['title']
    else: assert 'Do not upload a custom FTREE package' in finding['action']
