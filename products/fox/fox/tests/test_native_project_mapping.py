"""Real mapped-project guards; gateway/model boundaries are local fakes only."""
from copy import deepcopy
import json

import pytest

from fox import native_project_pipeline as pipeline
from fox.intake import checked_source, inventory
from fox.opaf import OpafError
from fox.project_conversion import assess_project_conversion
from test_native_project_pipeline import Harness, write


def mapped_harness(tmp_path, monkeypatch):
    h = Harness(tmp_path, monkeypatch)
    files = [checked_source("customers.xml", b'<FormModule Name="CUSTOMERS"><Block Name="MAIN" QueryDataSourceName="CUSTOMERS"><Item Name="ID"/><Item Name="TITLE"/></Block></FormModule>'),
             checked_source("customers.sql", b'CREATE TABLE CUSTOMERS (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(40) NOT NULL);')]
    plan = assess_project_conversion(files, project_id="test-project", project_name="Synthetic project",
                                     source_hash=inventory(files)["source_hash"])
    assert plan["state"] == "READY" and plan["rendering_spec"]["schema_version"] == 2
    h.plan = plan
    h.snapshot.update(files=files, source_hash=plan["source_hash"], plan_sha256=plan["plan_sha256"],
                      native_project=plan["rendering_spec"])
    write(h.job / "source-snapshot.json", h.snapshot)
    h.http_requests = []
    original_request = h.request
    def recorded_request(method, path, payload=None, binary=False):
        h.http_requests.append((method, path))
        return original_request(method, path, payload, binary)
    h.request = recorded_request
    return h


@pytest.mark.parametrize("missing", ["converter", "profile", "paired_target", "target_graph"])
def test_mapping_requires_complete_new_pair_before_any_post(tmp_path, monkeypatch, missing):
    h = mapped_harness(tmp_path, monkeypatch)
    if missing != "converter":
        h.capability["project_mapping"] = {**pipeline.PROJECT_MAPPING_CAPABILITY, "paired_profile_ready": True}
    if missing != "profile":
        h.profile.update(schema_version=2, profile_id=pipeline.PROFILE_ID, **pipeline.PROJECT_MAPPING_CAPABILITY)
        write(tmp_path / "profile.json", h.profile)
    if missing not in {"paired_target", "converter", "profile"}:
        h.target["scope"]["project_mapping"] = deepcopy(pipeline.PROJECT_MAPPING_CAPABILITY)
        h.target["opaf"]["roles"]["reviewer"]["graph_sha256"] = "f" * 64
    with pytest.raises(OpafError, match="NOT_READY|approved native model"):
        pipeline.run_native_project_job(h.job)
    assert not h.model_calls
    assert h.http_requests and all(method == "GET" for method, _ in h.http_requests)
    assert h.state is None


@pytest.mark.parametrize("field", ["storage_mapping_scope", "module_execution_scope", "native_project_schema_versions"])
def test_capability_does_not_accept_partial_or_unknown_mapping_contract(field):
    capability = {"schema_version": 1, "conversion_profiles": [pipeline.PROFILE_ID],
                  "project_protocol": pipeline.PROFILE_ID, "schema_preparation": True,
                  "project_mapping": {**pipeline.PROJECT_MAPPING_CAPABILITY, "paired_profile_ready": True}}
    profile = {"schema_version": 2, "profile_id": pipeline.PROFILE_ID, **pipeline.PROJECT_MAPPING_CAPABILITY}
    capability["project_mapping"].pop(field)
    class Gateway:
        def request(self, method, path):
            assert method == "GET" and path == "/fox/capabilities"
            return capability
    with pytest.raises(OpafError, match="NOT_READY"):
        pipeline._capability(Gateway(), {"schema_version": 2}, profile)
