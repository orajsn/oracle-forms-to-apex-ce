    (ddl("WORK_ITEMS").replace("GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY", "NOT NULL"), "EXPLICIT_KEY_REQUIRED"),
    (ddl("WORK_ITEMS")[:-2] + ", PRIMARY KEY (ID, TITLE));", "TABLE_CONSTRAINT_UNSUPPORTED"),
