"""Original-name project admission uses synthetic fixtures only; no source rewriting."""
from copy import deepcopy
import hashlib
import json

import pytest

from fox import native_source, project_conversion as planner
from test_project_conversion import assess, codes, ddl, module, pair, source, xml


def ordinary_pair(name="ALPHA", table="WORK_ITEMS", prompt="Title"):
    return pair(name, table, prompt)


def rehash(plan):
    plan["plan_sha256"] = hashlib.sha256(json.dumps(
        {key: value for key, value in plan.items() if key != "plan_sha256"},
        sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()


def binding(plan):
    return planner.module_execution_binding(plan, parent_job_id="fox-" + "a" * 20,
                                            module_id=plan["forms"][0]["module_id"])


def mappings(plan):
    return {form["table_name"]: form["storage_mapping"] for form in plan["forms"]}


def test_ordinary_two_forms_preserve_original_bytes_and_exact_versioned_contract():
    files = ordinary_pair() + ordinary_pair("BETA", "STATUS_LOG")
    files[0] = source(files[0]["name"], files[0]["text"], bom=True)
    original = deepcopy(files)
    plan = assess(files)
    assert files == original
    assert plan["state"] == "READY"
    spec = plan["rendering_spec"]
    assert set(spec) == {"schema_version", "profile_id", "data_mode", "project_id", "project_name",
                         "source_manifest_sha256", "forms"}
    assert spec["schema_version"] == 2 and spec["profile_id"] == "native-project-v1"
    assert spec["project_id"] == plan["project_id"] and spec["data_mode"] == "synthetic_test_only"
    for form in spec["forms"]:
        assert set(form) == {"module_id", "form_name", "source_name", "source_sha256", "native_form",
                             "ddl_sources", "storage_mapping"}
        mapping = form["storage_mapping"]
        original_spec = deepcopy(form["native_form"])
        original_spec["table_name"] = mapping["source_table_name"]
        assert mapping == planner.derive_storage_mapping(plan["project_id"], original_spec)
        assert mapping == planner.validate_storage_mapping(mapping, project_id=plan["project_id"],
                                                          native_form=form["native_form"])
        assert form["native_form"]["table_name"] == "FOX_NATIVE_" + mapping["identity_sha256"][:19].upper()
        assert len(form["native_form"]["table_name"]) == 30
        assert form["source_sha256"] == next(item["sha256"] for item in original if item["name"] == form["source_name"])
        assert all(ref == {"name": item["name"], "sha256": item["sha256"]}
                   for ref in form["ddl_sources"] for item in original if ref["name"] == item["name"])
        assert original_spec["columns"][0]["primary_key"] is True
    assert binding(plan)["schema_version"] == 2
    assert binding(plan)["scope"] == "fox-project-module-execution-v2"
    assert binding(plan)["storage_mapping"] == plan["forms"][0]["storage_mapping"]
    assert binding(plan)["ddl_sources"] == plan["forms"][0]["ddl_sources"]


