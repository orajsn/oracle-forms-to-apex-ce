def test_original_requiredness_conflicts_and_conflicting_ddl_still_block_whole_project():
    files = ordinary_pair()
    files[0] = source("alpha.xml", files[0]["text"].replace('Name="TITLE"', 'Name="TITLE" Required="true"'))
    files[1] = source("alpha.sql", ddl("WORK_ITEMS", nullable="NULL"))
    plan = assess(files + pair("BETA", "FOX_NATIVE_BETA"))
    assert plan["state"] == "BLOCKED" and plan["rendering_spec"] is None
    assert "ITEM_BEHAVIOR_REVIEW_REQUIRED" in codes(plan)
    with pytest.raises(planner.ProjectConversionInputError): binding(plan)
    conflict = assess(ordinary_pair() + [source("conflict.sql", ddl("WORK_ITEMS", "NUMBER"))])
    assert "SHARED_SCHEMA_CONFLICT" in codes(conflict) and "DDL_REQUIRED" not in codes(conflict)
    assert conflict["rendering_spec"] is None


@pytest.mark.parametrize("collision", ["truncated", "full"])
def test_storage_hash_collisions_fail_closed(monkeypatch, collision):
    original = planner._storage_identity_sha
    monkeypatch.setattr(planner, "_storage_identity_sha",
        lambda value: "a" * 64 if collision == "full" else "a" * 19 + original(value)[19:])
    with pytest.raises(planner.ProjectConversionInputError) as error:
        assess(ordinary_pair() + ordinary_pair("BETA", "STATUS_LOG"))
    assert error.value.code == "STORAGE_MAPPING_COLLISION"


@pytest.mark.parametrize("change", ["project", "mapping", "source_table", "ddl_hash", "subset", "extra_field"])
def test_rehashed_tampering_does_not_escape_mapping_or_complete_source_binding(change):
    plan = assess(ordinary_pair() + ordinary_pair("BETA", "STATUS_LOG"))
    if change == "project": plan["project_id"] = "other-project"
    if change == "mapping": plan["forms"][0]["storage_mapping"]["identity_sha256"] = "b" * 64
    if change == "source_table": plan["forms"][0]["table_name"] = "OTHER_TABLE"
    if change == "ddl_hash": plan["forms"][0]["ddl_sources"][0]["sha256"] = "c" * 64
    if change == "subset": plan["forms"] = plan["forms"][:1]
    if change == "extra_field": plan["forms"][0]["storage_mapping"]["copy_data"] = True
    if change in {"ddl_hash", "subset", "source_table"}:
        plan["rendering_spec"] = planner._rendering_spec(plan)
    rehash(plan)
    with pytest.raises(planner.ProjectConversionInputError): binding(plan)


