"""Checkpointed focused OPAF design -> ONE synthetic native APEX candidate.

``run_prototype_pipeline`` is called by the owning project worker, not a GET
route. Documents are the exact retained, reviewed/redacted source version.
``processing_approval_check(context) is True`` is required before EACH new
model call; it must check the owner's fresh source/destination approval.

The published mapper receives the focus request AT THE JSON ROOT. The reviewer
receives {request, candidate, candidate_sha256}. Observation uses a separate
{job_id, source_hash} identity; these fields must not alter the model protocol.

The default NativeBlueprintRenderer calls the existing converter's pure
renderer. Its ZIP is CANDIDATE APEXlang, not a validated/importable SQL export.
An injected converter adapter implements supports(stage), run_stage(stage,
request), recover_stage(stage, request). Recovery MUST be read-only. Stages:
validate -> prepare_schema -> import -> verify_runtime -> export. Receipts bind
stage, request_sha256, source_binding and plan_sha256. Stage-specific gates are
documented by _check_converter_receipt. Adapter implementations must retain and
validate actual SQLcl/Oracle/authenticated-browser evidence, not invent proof.
Export confirms generated bytes, NOT a complete-package reimport or clean-schema
installation. These unimplemented proof gates remain separately false and never
become technically_verified/download_ready merely because export completed.

One worker owns this directory. Completed immutable results are checked/reused;
pending POSTs are NEVER replayed. Originals are never rewritten. Business
acceptance is always false here, independently of every technical stage.
"""
