CONVERTER_STAGES = ('validate', 'prepare_schema', 'import', 'verify_runtime', 'export')
_SHA = re.compile(r'[0-9a-f]{64}\Z')


class NativeBlueprintRenderer:
    """Actual deterministic converter rendering; no SQLcl or Oracle operation."""

    def render(self, spec):
        # The app and converter are separate installation closures. A missing
        # converter is a real adapter blocker, never an invented rendered ZIP.
        from forms2apex.native_blueprint import deterministic_prototype_zip, prototype_trace
        return deterministic_prototype_zip(spec), prototype_trace(spec)


def _directory(path):
    if path.is_symlink():
        raise OpafError('Unsafe prototype checkpoint directory.')
    path.mkdir(exist_ok=True)


def _save_bytes_once(path, raw):
    if not isinstance(raw, bytes) or not raw or len(raw) > 20_000_000:
        raise OpafError('Prototype candidate exceeds the output bound.')
    digest = hashlib.sha256(raw).hexdigest()
    if path.is_symlink():
        raise OpafError('Unsafe prototype candidate path.')
    if path.exists():
        if not path.is_file() or path.stat().st_size != len(raw) or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise OpafError('Prototype candidate changed; original evidence preserved.')
        return digest
    fd, name = tempfile.mkstemp(prefix='.prototype-', dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        try:
            os.link(temporary, path)
        except FileExistsError:
            return _save_bytes_once(path, raw)
        _sync(path.parent)
    finally:
        temporary.unlink(missing_ok=True)
    return digest


def _save_artifact(path, value):
    """Larger local facts/plans use the same create-only durable byte pattern."""
    raw = json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False,
                     separators=(',', ':')).encode('utf-8')
    _save_bytes_once(path, raw)


def _artifact_json(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 20_000_000:
        raise OpafError('Prototype artifact is missing, oversized or unsafe.')
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        raise OpafError('Prototype artifact is unreadable; evidence retained.') from None


def _role(directory, name, client, role, request, identity, target_profile_loader,
          processing_approval_check, approval_context):
    """Observe identity separately without changing published model requests."""
    if client is not None:
        from .prototype_read_scope import forbid_execution
        forbid_execution()
    complete, pending = directory / (name + '.json'), directory / (name + '-intent.json')
    if len(json.dumps(request, ensure_ascii=False, allow_nan=False).encode('utf-8')) > 650_000:
        raise OpafError('Prototype model request exceeds the transport bound; select a smaller explicit focus.')
    binding = {'role': role, 'request_sha256': canonical_hash(request), **identity}
    if complete.exists() or complete.is_symlink():
        saved = _json(complete)
        if (saved.get('binding') != binding
                or saved.get('output_sha256') != canonical_hash(saved.get('output'))
                or saved.get('invocation', {}).get('request_sha256') != binding['request_sha256']
                or saved.get('model_environment_sha256') != canonical_hash(saved.get('model_environment'))):
            raise OpafError('Prototype role checkpoint changed; no automatic replay.')
        target = _json(directory / (name + '-target.json'))
        validate_model_environment(saved['model_environment'], target, name, identity, saved['invocation'])
        return saved['output'], saved['invocation']
    if pending.exists() or pending.is_symlink():
        raise OpafError('Prior prototype model result is uncertain; reconcile it without replay.')
    if processing_approval_check({**approval_context, 'role': name,
                                  'request_sha256': binding['request_sha256']}) is not True:
        raise OpafError('Fresh source-bound external-processing approval is required.')
    target = target_profile_loader()
    if target.get('opaf', {}).get('roles', {}).get(name) != role:
        raise OpafError('Prototype role differs from its approved target profile.')
    _save_once(directory / (name + '-target.json'), target)
    environment = client.observe_environment(role, identity, role_name=name, target_profile=target)
    # Only an observed environment and successful approval precede this intent.
    # Any failure after it requires operator reconciliation, not another POST.
    _save_once(pending, binding)
    try:
        output, invocation = client.invoke(role, request)
        if (invocation.get('request_sha256') != binding['request_sha256']
                or not re.fullmatch(r'[A-Za-z0-9_.:-]{1,128}', invocation.get('room_id', ''))
                or not _SHA.fullmatch(invocation.get('response_sha256', ''))):
            raise OpafError('Prototype invocation is not bound to the actual model request.')
        validate_model_environment(environment, target, name, identity, invocation)
        _save_once(complete, {'binding': binding, 'output': output,
                    'output_sha256': canonical_hash(output), 'invocation': invocation,
                    'model_environment': environment,
                    'model_environment_sha256': canonical_hash(environment)})
    except Exception:
        raise OpafError('Prototype model call did not seal a result; reconcile without replay.') from None
    return output, invocation


def _review_index(checkpoints, plan):
    from .prototype_mapping_epochs import technical_record, active_focus, read
    epoch = technical_record(checkpoints)
    if epoch is not None:
        packet = _artifact_json(checkpoints / 'packet.json')
        target = read(checkpoints / plan['requests'][0]['focus_id'] / 'mapper-target.json')
        views = []
        for request in plan['requests']:
            view = active_focus(checkpoints, packet, plan, request, target, views)
            if not view['checked']['approved_structured_design']:
                raise OpafError('Active epoch lacks approved reviewed design.')
            views.append(view)
        files = []
        # Include exact historical and active technical provenance, not owner
        # consent claims. The original FOX callback separately checks its DB.
        names = {name[len('prototype-pipeline/'):] for name in epoch['before_files'] if name.startswith('prototype-pipeline/')}
        base = checkpoints / 'epochs' / f"epoch-{epoch['epoch_number']:06d}"
        names.update(path.relative_to(checkpoints).as_posix() for path in base.rglob('*') if path.is_file())
        for name in sorted(names):
            path = checkpoints / name
            if path.is_symlink() or not path.is_file():
                raise OpafError('Epoch provenance is missing or linked.')
            files.append({'path': name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        return {'schema_version': 2, 'source_binding': plan['source_binding'], 'focus_plan_sha256': canonical_hash(plan),
                'epoch_sha256': canonical_hash(epoch), 'focuses': [view['proof'] for view in views], 'provenance_files': files}
    def row(request):
        child = checkpoints / request['focus_id']
        result = {'focus_id': request['focus_id'],
                  **{name + '_sha256': canonical_hash(_json(child / (name + '.json')))
                     for name in ('request', 'mapper', 'mapper-target', 'reviewer', 'reviewer-target', 'review-receipt')}}
        raw = _json(child / 'mapper.json')['output']
        _, receipt = resolved_mapper(child, request, raw)
        if receipt is not None:
            result.update({name[:-5] + '_sha256': canonical_hash(_json(child / name))
                           for name in RESOLUTION_ARTIFACTS})
        return result
    return {'source_binding': plan['source_binding'], 'focus_plan_sha256': canonical_hash(plan),
            'focuses': [row(request) for request in plan['requests']]}


def authorize_prototype_request(job: Path, request: dict) -> dict:
    """Read-only exact source/reviewer authority check for the private gateway.

    The caller selects ``job`` from its CONFIGURED private root and additionally
    checks persisted project ownership, destination and synthetic-scope consent.
    Do not resolve a filesystem path supplied by the request. This function
    reconstructs proofs from actual worker-owned artifacts; user booleans and
    claimed model approval are never authoritative.
    """
    from .prototype_read_scope import epoch_read_scope
    with epoch_read_scope(Path(job) / 'prototype-pipeline'):
        return _authorize_prototype_request(job, request)


def _authorize_prototype_request(job: Path, request: dict) -> dict:
    job = Path(job)
    checkpoints = job / 'prototype-pipeline'
    if job.is_symlink() or checkpoints.is_symlink() or not checkpoints.is_dir():
        raise OpafError('Prototype authority directory is unsafe or missing.')
    binding = _json(checkpoints / 'binding.json')
    manifest = _json(checkpoints / 'sources-manifest.json')
    if ((request.get('job_id'), request.get('project_id'), request.get('source_binding')) !=
            (job.name, binding.get('project_id'), binding.get('source_binding'))
            or binding.get('job_id') != job.name or binding.get('approved_policy_id') != POLICY_ID
            or (checkpoints / 'sources').is_symlink()):
        raise OpafError('Prototype authority differs from its retained source version.')
    documents = []
    if not isinstance(manifest.get('files'), list) or not 1 <= len(manifest['files']) <= 4:
        raise OpafError('Prototype source manifest is outside its bounded contract.')
    for index, source in enumerate(manifest.get('files', [])):
        # Paths are fixed by this module, never interpreted from source names.
        path = checkpoints / 'sources' / f'source-{index:03}.xml'
        if (not isinstance(source, dict) or path.is_symlink() or not path.is_file()
                or path.stat().st_size > 5 * 1024 * 1024 or path.stat().st_size != source.get('bytes')):
            raise OpafError('Prototype retained source is missing or unsafe.')
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != source.get('sha256'):
            raise OpafError('Prototype retained source bytes changed.')
        documents.append((source['name'], raw))
    packet = local_packet(documents)
    if packet != _artifact_json(checkpoints / 'packet.json'):
        raise OpafError('Prototype facts do not match fresh retained source bytes.')
    plan = build_focus_plan(documents, expected_source_binding=binding['source_binding'],
                            approved_chunk_hashes=manifest['selected_chunk_hashes'],
                            max_owned_objects=bound_focus_limit(binding))
    if canonical_hash(plan) != binding['focus_plan_sha256']:
        raise OpafError('Prototype focus selection differs from its retained binding.')
    candidates = []
    identity = {'job_id': job.name, 'source_hash': binding['source_binding']}
    from .prototype_mapping_epochs import technical_record, active_focus
    epoch = technical_record(checkpoints)
    views = []
    for focus in plan['requests']:
        if epoch is not None:
            target = _json(checkpoints / plan['requests'][0]['focus_id'] / 'mapper-target.json')
            view = active_focus(checkpoints, packet, plan, focus, target, views)
            if not view['checked']['approved_structured_design']:
                raise OpafError('Active epoch source design is not approved.')
            views.append(view); candidates.append(view['candidate'])
            continue
        child = checkpoints / focus['focus_id']
        if child.is_symlink() or _json(child / 'request.json') != focus:
            raise OpafError('Prototype authority focus request changed.')
        mapper_saved, reviewer_saved = _json(child / 'mapper.json'), _json(child / 'reviewer.json')
        candidate, mapper = _role(child, 'mapper', None, mapper_saved['binding']['role'],
                                  focus, identity, None, None, None)
        candidate, _ = resolved_mapper(child, focus, candidate)
        review, reviewer = _role(child, 'reviewer', None, reviewer_saved['binding']['role'],
            {'request': focus, 'candidate': candidate, 'candidate_sha256': canonical_hash(candidate)},
            identity, None, None, None)
        roles = {name: _json(child / (name + '.json'))['binding']['role'] for name in ('mapper', 'reviewer')}
        if (canonical_hash(roles) != binding['profile_sha256']
                or mapper['workflow_id'].upper() == reviewer['workflow_id'].upper()
                or mapper['room_id'] == reviewer['room_id']):
            raise OpafError('Prototype authority requires the exact independently executed roles.')
        checked = forms_design_review.validate_design_review(focus, candidate, review)
        if not checked['approved_structured_design'] or _json(child / 'review-receipt.json') != checked:
            raise OpafError('Prototype authority lacks an approved source-bound design review.')
        candidates.append(candidate)
    merged = merge_focus_blueprints(documents, plan, candidates)
    native_plan = build_native_prototype_plan(documents, merged['blueprint'],
        project_id=binding['project_id'], project_name=binding['project_name'], approved_policy_id=POLICY_ID)
    if (merged != _artifact_json(checkpoints / 'merged-blueprint.json')
            or native_plan != _artifact_json(checkpoints / 'native-plan.json')
            or request.get('rendering_spec') != native_plan['rendering_spec']
            or request.get('plan_sha256') != native_plan['plan_sha256']):
        raise OpafError('Prototype converter plan differs from the reviewed source reconstruction.')
    index = _review_index(checkpoints, plan)
    if canonical_hash(_json(checkpoints / 'review-index.json')) != canonical_hash(index):
        raise OpafError('Prototype reviewer authority index changed.')
    authority = {'schema_version': 1, 'scope': 'fox-prototype-source-authority-v1',
                 'binding_sha256': canonical_hash(binding), 'sources_manifest_sha256': canonical_hash(manifest),
                 'review_index_sha256': canonical_hash(index)}
    archive = checkpoints / 'candidate-apexlang.zip'
    rendered = _artifact_json(checkpoints / 'rendered.json')
    if (request.get('source_authority') != authority or archive.is_symlink()
            or not archive.is_file() or archive.stat().st_size > 20_000_000
            or hashlib.sha256(archive.read_bytes()).hexdigest() != request.get('rendered_zip_sha256')
            or rendered.get('zip_sha256') != request.get('rendered_zip_sha256')
            or rendered.get('plan_sha256') != native_plan['plan_sha256']):
        raise OpafError('Prototype candidate is not bound to its private source/reviewer authority.')
    return request


def _check_converter_receipt(stage, request, value):
    """Validate binding and truthful minimum gates, never substitute for proof.

    validate: passed=True. prepare_schema: ready_for_import=True.
    import: imported=True, positive application_id.
    verify_runtime: passed=True, authenticated=True, business_pages_tested=True.
    export: exported=True, package_sha256=SHA256. Adapter additionally verifies
    the exact package and browser evidence; an HTTP200/login page is not proof.
    """
    expected = {'stage': stage, 'request_sha256': canonical_hash(request),
                'source_binding': request['source_binding'], 'plan_sha256': request['plan_sha256']}
    if not isinstance(value, dict) or any(value.get(key) != item for key, item in expected.items()):
        raise OpafError('Prototype converter receipt is stale or unbound.')
    gates = {'validate': ('passed',), 'prepare_schema': ('ready_for_import',),
             'import': ('imported',),
             'verify_runtime': ('passed', 'authenticated', 'business_pages_tested'),
             'export': ('exported',)}
    if any(value.get(key) is not True for key in gates[stage]):
        raise OpafError('Prototype converter stage has not passed its technical gate.')
    if stage == 'import' and (type(value.get('application_id')) is not int or value['application_id'] < 1):
        raise OpafError('Prototype import lacks one confirmed native application.')
    if stage == 'export' and (not isinstance(value.get('package_sha256'), str)
                              or not _SHA.fullmatch(value['package_sha256'])):
        raise OpafError('Prototype export lacks its exact package hash.')
    if value.get('business_behavior_accepted') not in (None, False):
        raise OpafError('Technical adapter cannot record business acceptance.')
    return value


def run_prototype_pipeline(job: Path, documents: list[tuple[str, bytes]], *,
                           project_id, project_name, expected_source_binding,
                           approved_chunk_hashes, approved_policy_id, opaf_client,
                           profile, target_profile_loader, processing_approval_check,
                           converter_adapter=None, renderer=None, focus_schema_version=1):
    """Return safe stage facts and evidence paths; never a business acceptance.

    Run behind the project's single-worker/ownership guard. The route owns
    destination permission, consent persistence and source selection. This
    function repeats exact source/hash/selection checks and never uses caller
    supplied facts. Checkpoint paths are INTERNAL, not public download grants.
    """
    job = Path(job)
    if not re.fullmatch(r'fox-[a-f0-9]{20}', job.name):
        raise OpafError('Invalid prototype run identity.')
    if approved_policy_id != POLICY_ID:
        raise OpafError('Explicit synthetic prototype scope is required.')
    if (not isinstance(project_id, str) or not forms_native_plan._PROJECT_ID.fullmatch(project_id)
            or not forms_native_plan._safe_label(project_name)):
        raise OpafError('Prototype project identity and name must satisfy the native rendering contract.')
    if (not isinstance(profile, dict) or any(not isinstance(profile.get(name), dict)
            for name in ('mapper', 'reviewer'))
            or any(not isinstance(profile[name].get('workflow_id'), str) for name in ('mapper', 'reviewer'))
            or profile['mapper'].get('workflow_id', '').upper() == profile['reviewer'].get('workflow_id', '').upper()):
        raise OpafError('Prototype requires separately configured mapper and reviewer workflows.')
    packet = local_packet(documents)
    strategy = {'schema_version': focus_schema_version}
    if type(focus_schema_version) is int and focus_schema_version == 2:
        strategy['max_owned_objects'] = FOCUS_MAX_OWNED_OBJECTS
    limit = bound_focus_limit(strategy)
    plan = build_focus_plan(documents, expected_source_binding=expected_source_binding,
                            approved_chunk_hashes=approved_chunk_hashes, max_owned_objects=limit)
    _directory(job)
    checkpoints = job / 'prototype-pipeline'
    _directory(checkpoints)
    binding = {**strategy, 'job_id': job.name, 'project_id': project_id,
               'project_name': project_name, 'source_binding': packet['source_binding'],
               'focus_plan_sha256': canonical_hash(plan),
               'profile_sha256': canonical_hash({name: profile[name] for name in ('mapper', 'reviewer')}),
               'approved_policy_id': approved_policy_id}
    _save_once(checkpoints / 'binding.json', binding)
    sources = checkpoints / 'sources'
    _directory(sources)
    manifest = {'source_binding': packet['source_binding'],
                'selected_chunk_hashes': dict(approved_chunk_hashes),
                'files': [{'name': name, 'sha256': hashlib.sha256(raw).hexdigest(), 'bytes': len(raw)}
                          for name, raw in documents]}
    _save_once(checkpoints / 'sources-manifest.json', manifest)
    for index, (_, raw) in enumerate(documents):
        _save_bytes_once(sources / f'source-{index:03}.xml', raw)
    _save_artifact(checkpoints / 'packet.json', packet)
    # Large plans remain partitioned: the existing durable JSON primitive has
    # a two-megabyte per-checkpoint cap, lower than the aggregate focus budget.
    _save_once(checkpoints / 'assessment.json', {
        'source_binding': packet['source_binding'], 'source_count': len(packet['sources']),
        'source_objects': plan['total_source_objects'], 'focus_count': len(plan['requests'])})
    facts = {'native_source_rendered': False, 'sqlcl_validated': False,
             'schema_prepared': False, 'import_verified': False,
             'runtime_verified': False, 'native_apex_generated': False,
             'package_reimport_passed': False, 'clean_schema_install_passed': False,
             'technically_verified': False, 'business_behavior_accepted': False,
             'download_ready': False}
    result = {'schema_version': 1, 'scope': 'fox-prototype-pipeline-v1',
              'job_id': job.name, 'source_binding': packet['source_binding'],
              'status': 'RUNNING', 'stage': 'mapping', 'facts': facts,
              'assessment': _json(checkpoints / 'assessment.json'),
              'artifacts': {'checkpoint_directory': str(checkpoints)}}
    from .prototype_mapping_epochs import technical_record
    from .prototype_container_epoch import NUMBER as CONTAINER_EPOCH
    current_epoch = technical_record(checkpoints)
    if current_epoch is not None and current_epoch['epoch_number'] == CONTAINER_EPOCH:
        result['mapping_epoch_sha256'] = canonical_hash(current_epoch)
    candidates, reviews = [], []
    identity = {'job_id': job.name, 'source_hash': packet['source_binding']}
    approval_context = {**binding, 'selected_chunk_hashes': dict(approved_chunk_hashes)}
    from .prototype_mapping_epochs import active_focus
    views = []
    for request in plan['requests']:
        target = (target_profile_loader() if target_profile_loader is not None else
                  _json(checkpoints / request['focus_id'] / 'mapper-target.json'))
        view = active_focus(checkpoints, packet, plan, request, target, views,
            runtime={'opaf_client': opaf_client, 'target_profile_loader': target_profile_loader,
                     'processing_approval_check': processing_approval_check, 'approval_context': approval_context})
        candidate, checked = view['candidate'], view['checked']
        reviews.append(checked)
        if not checked['approved_structured_design']:
            result.update(status='CHANGES_REQUIRED', stage='reviewing', blocked_focus_id=request['focus_id'])
            return result
        candidates.append(candidate)
        views.append(view)
    merged = merge_focus_blueprints(documents, plan, candidates)
    _save_artifact(checkpoints / 'merged-blueprint.json', merged)
    native_plan = build_native_prototype_plan(documents, merged['blueprint'],
        project_id=project_id, project_name=project_name, approved_policy_id=approved_policy_id)
    _save_artifact(checkpoints / 'native-plan.json', native_plan)
    review_index = _review_index(checkpoints, plan)
    _save_once(checkpoints / 'review-index.json', review_index)
    authority = {'schema_version': 1, 'scope': 'fox-prototype-source-authority-v1',
                 'binding_sha256': canonical_hash(binding), 'sources_manifest_sha256': canonical_hash(manifest),
                 'review_index_sha256': canonical_hash(review_index)}
    result.update(stage='render', plan_sha256=native_plan['plan_sha256'],
                  review_count=len(reviews), coverage=native_plan['coverage'])
    result['artifacts'].update(native_plan=str(checkpoints / 'native-plan.json'),
                               merged_blueprint=str(checkpoints / 'merged-blueprint.json'))
    if not native_plan['rendering_spec']['blocks']:
        result.update(status='BLOCKED_MAPPING', reason='No source block has a renderable native prototype mapping.')
        return result
    try:
        raw, trace = (renderer or NativeBlueprintRenderer()).render(native_plan['rendering_spec'])
    except ImportError:
        result.update(status='BLOCKED_ADAPTER', reason='Native prototype renderer is not installed in this worker.')
        return result
    archive = checkpoints / 'candidate-apexlang.zip'
    digest = _save_bytes_once(archive, raw)
    _save_artifact(checkpoints / 'rendered.json', {'source_binding': packet['source_binding'],
               'plan_sha256': native_plan['plan_sha256'], 'zip_sha256': digest, 'trace': trace})
    facts['native_source_rendered'] = True
    result['artifacts'].update(candidate_apexlang=str(archive), candidate_apexlang_sha256=digest)
    prior = {}
    for stage in CONVERTER_STAGES:
        result['stage'] = stage
        request = {'schema_version': 1, 'scope': 'fox-prototype-converter-request-v1',
                   'job_id': job.name, 'project_id': project_id,
                   'source_binding': packet['source_binding'], 'plan_sha256': native_plan['plan_sha256'],
                   'rendering_spec': native_plan['rendering_spec'], 'rendered_zip_sha256': digest,
                   'source_authority': authority,
                   'prior_receipts': dict(prior)}
        complete, pending = checkpoints / (stage + '.json'), checkpoints / (stage + '-intent.json')
        if complete.exists() or complete.is_symlink():
            receipt = _check_converter_receipt(stage, request, _json(complete))
        elif converter_adapter is None or not converter_adapter.supports(stage):
            result.update(status='BLOCKED_ADAPTER', reason='The converter does not provide this prototype stage.')
            return result
        else:
            if (pending.exists() or pending.is_symlink()) and _json(pending) != {'request_sha256': canonical_hash(request)}:
                raise OpafError('Prototype converter intent changed; no automatic replay.')
            # A GET-only recovery is tried even on a first call: this permits
            # retaining a completed remote operation after lost local evidence.
            receipt = converter_adapter.recover_stage(stage, request)
            if receipt is None:
                if pending.exists():
                    result.update(status='RECONCILIATION_REQUIRED',
                                  reason='A prior converter operation is uncertain; no operation was replayed.')
                    return result
                _save_once(pending, {'request_sha256': canonical_hash(request)})
                try:
                    receipt = converter_adapter.run_stage(stage, request)
                except Exception:
                    raise OpafError('Prototype converter result is uncertain; reconcile without replay.') from None
            receipt = _check_converter_receipt(stage, request, receipt)
            _save_once(complete, receipt)
        prior[stage] = receipt
        facts[{'validate': 'sqlcl_validated', 'prepare_schema': 'schema_prepared',
               'import': 'import_verified', 'verify_runtime': 'runtime_verified',
               'export': 'native_apex_generated'}[stage]] = True
    # A browser check of the generated app and a successful export are useful
    # independent facts. Neither establishes that the exact final package can
    # be reimported or installed into a clean schema. This pipeline currently
    # has no validators for those two gates: even adapter-supplied booleans must
    # not promote them, technical verification or normal download permission.
    result.update(status='APEX_GENERATED', stage='complete', converter_receipts=prior,
                  reason='APEX generated; exact-package reimport and clean-schema installation proof remain pending.')
    return result
