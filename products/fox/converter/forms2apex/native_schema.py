"""Deterministic, create-only synthetic DDL for the declared native profile.

This is an explicit prerequisite script, not customer-schema inference and not
an automatic database migration. Existing objects are never altered/dropped.
"""
from .native_contract import validate_native_spec


def render_native_schema(spec):
    value = validate_native_spec(spec)
    columns = []
    for column in value['columns']:
        kind = column['data_type']
        if kind == 'VARCHAR2':
            kind += '(' + str(column['length']) + ')'
        line = column['name'] + ' ' + kind
        if column['identity']:
            line += ' GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY'
        elif not column['nullable']:
            line += ' NOT NULL'
        columns.append('  ' + line)
    return ('-- FOX native-table-form-v1: synthetic test schema only.\n'
            '-- Run only in the explicitly selected empty test parsing schema.\n'
            '-- Existing tables cause failure; no ALTER, DROP, grants or data loads.\n'
            'whenever sqlerror exit failure rollback\n'
            'whenever oserror exit failure rollback\n'
            'set define off\n'
            'CREATE TABLE ' + value['table_name'] + ' (\n' + ',\n'.join(columns) + '\n);\n')
