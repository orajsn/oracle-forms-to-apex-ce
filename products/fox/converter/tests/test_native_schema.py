import pytest
from forms2apex.native_schema import render_native_schema


def spec():
    return {'profile_id':'native-table-form-v1','data_mode':'synthetic_test_only',
        'table_name':'FOX_NATIVE_BETA','columns':[
            {'name':'ID','data_type':'NUMBER','nullable':False,'label':'ID','identity':True,'primary_key':True},
            {'name':'TITLE','data_type':'VARCHAR2','length':100,'nullable':False,'label':'Title'},
            {'name':'AMOUNT','data_type':'NUMBER','nullable':False,'label':'Amount'},
            {'name':'DUE_DATE','data_type':'DATE','nullable':True,'label':'Due date'}]}


def test_create_only_explicit_typed_schema():
    sql=render_native_schema(spec())
    assert 'CREATE TABLE FOX_NATIVE_BETA' in sql
    assert 'ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY' in sql
    assert 'TITLE VARCHAR2(100) NOT NULL' in sql
    assert 'AMOUNT NUMBER NOT NULL' in sql and 'DUE_DATE DATE\n' in sql
    executable='\n'.join(line for line in sql.splitlines() if not line.startswith('--'))
    for token in ('DROP','ALTER','INSERT','MERGE','GRANT','CREATE USER'):
        assert token not in executable.upper()
    assert 'whenever sqlerror exit failure rollback' in sql
    assert executable.count(';')==1


@pytest.mark.parametrize('name',['CUSTOMER_TABLE','FOX_NATIVE_X; DROP USER X','FOX_NATIVE_X.Y','"FOX_NATIVE_X"'])
def test_invalid_table_never_reaches_sql(name):
    value=spec();value['table_name']=name
    with pytest.raises(ValueError):render_native_schema(value)


def test_labels_never_interpolated_into_ddl():
    value=spec();value['columns'][1]['label']="Jason's title"
    assert "Jason" not in render_native_schema(value)
