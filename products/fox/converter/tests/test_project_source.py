"""Original byte-bound source plans, including ordinary names and mapped storage."""
from copy import deepcopy
import pytest

from fox_source_contract.intake import checked_source, inventory
from fox_source_contract.project_conversion import assess_project_conversion, derive_storage_mapping
from forms2apex.project_source import validate_project_sources


def mapped_snapshot(*, project_id="ordinary-project", bom=False, shared=False):
    files = []
    for index, name in enumerate(("CUSTOMERS", "ORDERS")):
        table = "CUSTOMERS" if shared else name
        xml = (f'<FormModule Name="{name}"><Block Name="MAIN" QueryDataSourceName="{table}">'
               f'<Item Name="ID"/><Item Name="TITLE" Prompt="Title {index + 1}"/></Block></FormModule>').encode()
        if bom:
            xml = b"\xef\xbb\xbf" + xml
        files.append(checked_source(name.lower() + ".xml", xml))
        if not shared or index == 0:
            sql = (f"CREATE TABLE {table} (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, "
                   "TITLE VARCHAR2(40) NOT NULL);").encode()
            files.append(checked_source(name.lower() + ".sql", sql))
    source_hash = inventory(files)["source_hash"]
    plan = assess_project_conversion(files, project_id=project_id, project_name="Ordinary source project", source_hash=source_hash)
    assert plan["state"] == "READY"
    return {"source_hash": source_hash, "files": files, "conversion_profile": "native-project-v1",
            "project_id": project_id, "project_name": "Ordinary source project", "plan_sha256": plan["plan_sha256"],
            "native_project": plan["rendering_spec"]}, plan


@pytest.mark.parametrize("bom", [False, True])
@pytest.mark.parametrize("shared", [False, True])
def test_complete_original_sources_recompute_the_exact_mapped_plan(bom, shared):
    snap, plan = mapped_snapshot(bom=bom, shared=shared)
    before = deepcopy(snap)
    actual = validate_project_sources(snap["native_project"], snap["files"],
        project_id=snap["project_id"], plan_sha256=snap["plan_sha256"])
    assert actual == plan and snap == before
    assert actual["rendering_spec"]["schema_version"] == 2
    source_hashes = {source["name"]: source["sha256"] for source in snap["files"]}
    for form in actual["rendering_spec"]["forms"]:
        assert form["source_sha256"] == source_hashes[form["source_name"]]
        assert all(reference["sha256"] == source_hashes[reference["name"]] for reference in form["ddl_sources"])


@pytest.mark.parametrize("change", ["project", "source", "target", "ddl_ref", "omitted", "bytes", "forged_schema"])
def test_client_mapping_cannot_replace_original_source_authority(change):
    snap, _ = mapped_snapshot()
    project = snap["native_project"]
    form = project["forms"][0]
    if change == "project": snap["project_id"] = "other-project"
    elif change == "source": form["storage_mapping"]["source_table_name"] = "FAKE"
    elif change == "target": form["native_form"]["table_name"] = "FOX_NATIVE_FAKE"
    elif change == "ddl_ref": form["ddl_sources"][0]["sha256"] = "f" * 64
    elif change == "omitted": snap["files"].pop()
    elif change == "bytes": snap["files"][0]["text"] += " "
    else:
        source = deepcopy(form["native_form"])
        source["columns"][1]["length"] = 80
        source["table_name"] = form["storage_mapping"]["source_table_name"]
        form["storage_mapping"] = derive_storage_mapping(snap["project_id"], source)
        form["native_form"] = {**source, "table_name": form["storage_mapping"]["target_table_name"]}
    with pytest.raises(ValueError):
        validate_project_sources(project, snap["files"], project_id=snap["project_id"], plan_sha256=snap["plan_sha256"])
