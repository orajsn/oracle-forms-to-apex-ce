def test_one_rejected_form_blocks_the_complete_project(tmp_path):
    w, root, inventory, request, _, _ = make_project(tmp_path, reviewed=False)
    profile = load_target_profile(PROFILE_PATH)
    for index, row in enumerate(inventory["forms"]):
        payload = form_payload(root, row, profile)
        if index == 1:
            payload["review"].update(verdict="reject", blocking_findings=["Source owner decision required"])
        receipt = reviews.record_project_form_review(root, row["module_id"], payload, *w.review_identity(), target_profile=profile)
        request["form_reviews"].append({"module_id": row["module_id"], "receipt_sha256": receipt["receipt_sha256"]})
    with pytest.raises(ValueError, match="approval"):
        reviews.aggregate_project_review(root, request, *w.review_identity())
    assert not (root / "project-review.json").exists()


