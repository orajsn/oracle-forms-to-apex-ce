def test_twenty_form_large_source_inspection_is_compact_and_replayable(tmp_path):
    from fox_source_contract.intake import checked_source, inventory
    from fox_source_contract.project_conversion import assess_project_conversion
    w, _ = workflow(tmp_path)
    files = []
    for index in range(20):
        name, table = f"FORM_{index:02d}", f"FOX_NATIVE_{index:02d}"
        xml = (f'<FormModule Name="{name}"><Block Name="MAIN" QueryDataSourceName="{table}">'
               '<Item Name="ID"/><Item Name="TITLE" Prompt="Title"/></Block>' + " " * 10_000 + '</FormModule>')
        sql = f'CREATE TABLE {table} (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(40) NOT NULL);'
        files.extend([checked_source(name + ".xml", xml.encode()), checked_source(name + ".sql", sql.encode())])
    source_hash = inventory(files)["source_hash"]
    plan = assess_project_conversion(files, project_id="large-project", project_name="Twenty form project", source_hash=source_hash)
    assert plan["state"] == "READY"
    jid = "fox-" + "3" * 20
    reviews.stage_project_snapshot(w.settings.jobs_root, jid, {"source_hash": source_hash, "files": files,
        "conversion_profile": "native-project-v1", "project_id": "large-project", "project_name": "Twenty form project",
        "plan_sha256": plan["plan_sha256"], "native_project": plan["rendering_spec"]})
    first = w.inspect(jid)
    assert len(first["forms"]) == 20 and len(first["shared_inventory"]["modules"]) == 40
    assert (w.store.require(jid) / "normalized-forms-inventory.json").stat().st_size < 1_000_000
    assert w.inspect(jid) == first
