@pytest.mark.parametrize("target", ["source", "child_review", "draft", "trace"])
def test_mutation_invalidates_whole_project(tmp_path, target):
    w, root, inventory, _, aggregate, _ = make_project(tmp_path)
    w.generate(root.name, json.dumps(aggregate["candidate"]))
    path = {"source": root / "intake/alpha.xml", "child_review": reviews.child_root(root, inventory["forms"][0]["module_id"]) / "native-review.json",
            "draft": root / "apexlang/application.apx", "trace": root / "source-to-apex.json"}[target]
    path.write_bytes(path.read_bytes() + b" ")
    if target == "child_review":
        value = json.loads(path.read_bytes()); value["review"]["notes"] = "changed"; path.write_text(json.dumps(value))
    with pytest.raises((ValueError, RuntimeError)):
        w.assert_artifact_binding(root.name)


