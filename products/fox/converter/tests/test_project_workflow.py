def sources(*, bom=False, business=False):
    from fox_source_contract.intake import checked_source
    result = []
    for name in ("ALPHA", "BETA"):
        xml = (f'<FormModule Name="{name}"><Block Name="MAIN" QueryDataSourceName="FOX_NATIVE_{name}">'
               '<Item Name="ID"/><Item Name="TITLE" Prompt="Title"/></Block>'
               + ('<Trigger Name="WHEN-VALIDATE-ITEM" TriggerText="null;"/>' if business and name == "BETA" else '')
               + '</FormModule>\r\n')
        sql = f'CREATE TABLE FOX_NATIVE_{name} (ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, TITLE VARCHAR2(40) NOT NULL);\r\n'
        for suffix, text in (("xml", xml), ("sql", sql)):
            raw = (b'\xef\xbb\xbf' if bom else b'') + text.encode()
            result.append(checked_source(name.lower() + "." + suffix, raw))
    return result


def snapshot(*, bom=False, business=False):
    from fox_source_contract.project_conversion import assess_project_conversion
    from fox_source_contract.intake import inventory
    files = sources(bom=bom, business=business)
    source_hash = inventory(files)["source_hash"]
    plan = assess_project_conversion(files, project_id="test-project", project_name="Synthetic test project", source_hash=source_hash)
    return {"source_hash": source_hash, "files": files, "conversion_profile": "native-project-v1",
            "project_id": "test-project", "project_name": "Synthetic test project", "plan_sha256": plan["plan_sha256"],
            "native_project": plan["rendering_spec"]}, plan


def workflow(tmp_path):
    profile = load_target_profile(PROFILE_PATH)
    role = profile["opaf"]["roles"]
    jobs = tmp_path / "j"
    jobs.mkdir()
    settings = Settings(jobs, Path("/never-run-sqlcl"), "F2A_APEX", "FORMS2APEX_POC",
        profile["apex"]["ords_origin"] + "/ords", role["mapper"]["model"], role["reviewer"]["model"],
        "127.0.0.1", 8090, "x" * 48, role["mapper"]["workflow_id"], role["reviewer"]["workflow_id"], PROFILE_PATH)
    return ProjectWorkflow(settings), profile


def form_payload(root, row, profile):
    inventory = row["inventory"]
    candidate = {"job_id": row["child_job_id"], "template_id": TEMPLATE_ID,
        "data_classification": "synthetic_or_stub_only", "generator": {"model": profile["opaf"]["roles"]["mapper"]["model"]},
        "native_form": inventory["approved_native_form"], "remediation_items": inventory["remediation_items"],
        "mapping_summary": "Reviewed synthetic query/insert/update table mapping; no business code inferred."}
    payload = {"job_id": row["child_job_id"], "source_hash": row["source_hash"], "candidate": candidate,
               "review": {"verdict": "approve", "candidate_sha256": candidate_sha256(candidate), "notes": "Independent fixture review", "blocking_findings": []},
               "model_environment": {}}
    for role, second in (("mapper", 0), ("reviewer", 2)):
        invocation = {**profile["opaf"]["roles"][role], "room_id": role + "-" + row["module_id"],
                      "request_sha256": "a" * 64, "response_sha256": "b" * 64,
                      "started_at_utc": f"2026-10-25T00:00:0{second}Z", "completed_at_utc": f"2026-10-25T00:00:0{second + 1}Z"}
        payload[role + "_invocation"] = invocation
        payload["model_environment"][role] = {"schema_version": 1, "scope": "opaf-model-environment-v1",
            "trust_boundary": "authenticated_fox_executor_not_vendor_attestation", "job_id": row["child_job_id"],
            "role": role, "source_manifest_sha256": row["source_hash"], "target_profile_sha256": target_profile_sha256(profile),
            "observed_at_utc": invocation["started_at_utc"],
            "opaf": {key: profile["opaf"][key] for key in ("base_url", "certificate_sha256", "model_authentication", "version_number", "build_id")},
            "workflow": {**profile["opaf"]["roles"][role], "published": True}, "opaf_version": profile["tested_versions"]["opaf"]}
    if "storage_mapping" in inventory:
        request = reviews.project_model_request(root, row)
        payload["mapper_invocation"]["request_sha256"] = reviews.digest(request)
        payload["reviewer_invocation"]["request_sha256"] = reviews.digest({
            **request, "candidate": candidate, "candidate_sha256": candidate_sha256(candidate)})
    return payload


def make_project(tmp_path, *, bom=False, reviewed=True):
    w, profile = workflow(tmp_path)
    job_id = "fox-" + "1" * 20
    snap, plan = snapshot(bom=bom)
    reviews.stage_project_snapshot(w.settings.jobs_root, job_id, snap)
    inventory = w.inspect(job_id)
    root = w.store.require(job_id)
    request = {"job_id": job_id, "source_hash": snap["source_hash"], "form_reviews": []}
    if reviewed:
        for row in inventory["forms"]:
            receipt = reviews.record_project_form_review(root, row["module_id"], form_payload(root, row, profile),
                                                        *w.review_identity(), target_profile=profile)
            request["form_reviews"].append({"module_id": row["module_id"], "receipt_sha256": receipt["receipt_sha256"]})
        aggregate = reviews.aggregate_project_review(root, request, *w.review_identity())
    else:
        aggregate = None
    return w, root, inventory, request, aggregate, plan


def validate_project(tmp_path, monkeypatch):
    w, root, inventory, request, aggregate, plan = make_project(tmp_path)
    w.generate(root.name, json.dumps(aggregate["candidate"]))
    monkeypatch.setattr(w, "native_target_preflight", lambda job, action: {"action": action, "isolated_test": True})
    monkeypatch.setattr(w, "assert_native_preflight_fresh", lambda *args: None)
    def validate(sqlcl, source, log):
        assert source.is_dir() and len(list((source / "pages").glob("*.apx"))) == 6
        log.write_text("isolated SQLcl whole-project boundary")
        return {"passed": True}
    monkeypatch.setattr("forms2apex.project_workflow.validate_apexlang", validate)
    w.validate(root.name)
    return w, root, aggregate


@pytest.mark.parametrize("bom", [False, True])
def test_complete_sources_reviews_and_deterministic_single_app(tmp_path, bom):
    w, root, inventory, request, aggregate, plan = make_project(tmp_path, bom=bom)
    from fox_source_contract.project_conversion import module_execution_binding
    for row in inventory["forms"]:
        assert row["binding"] == module_execution_binding(plan, parent_job_id=root.name, module_id=row["module_id"])
        assert row["inventory"]["project_module"]["module_id"] == row["module_id"]
        assert "modules" not in row["inventory"]
        assert row["inventory"]["shared_inventory_sha256"] == reviews.digest(inventory["shared_inventory"])
        projection = row["inventory"]["source_projection"]
        assert row["inventory"]["source_projection_sha256"] == reviews.digest(projection)
        assert projection["source_manifest_sha256"] == inventory["source_hash"]
        assert row["inventory"]["source_projection_sha256"] != inventory["source_hash"]
        chosen = {source["name"] for source in projection["sources"]}
        projected = [module for module in inventory["shared_inventory"]["modules"] if module["file"] in chosen]
        assert len(projected) == 2
        assert row["inventory"]["project_module"]["source_name"] in chosen
    assert w.inspect(root.name) == inventory
    result = w.generate(root.name, json.dumps(aggregate["candidate"]))
    assert result["application_count"] == 1 and result["form_count"] == 2
    assert len(list((root / "apexlang").glob("application.apx"))) == 1
    assert len(list((root / "apexlang/pages").glob("*.apx"))) == 6
    assert w.assert_artifact_binding(root.name)["template_id"] == "sqlcl-26.1.2-fox-project-v1"
    assert reviews.verify_project_review(root, aggregate["candidate"], *w.review_identity()) == aggregate


@pytest.mark.parametrize("mutation", ["omitted", "duplicate", "changed_hash"])
def test_aggregate_requires_every_exact_form_review(tmp_path, mutation):
    w, root, inventory, request, aggregate, plan = make_project(tmp_path)
    changed = deepcopy(request)
    if mutation == "omitted": changed["form_reviews"].pop()
    if mutation == "duplicate": changed["form_reviews"][1] = changed["form_reviews"][0]
    if mutation == "changed_hash": changed["form_reviews"][0]["receipt_sha256"] = "0" * 64
    with pytest.raises((ValueError, RuntimeError)):
        reviews.aggregate_project_review(root, changed, *w.review_identity())


