"""Assess supplied readable Forms/DDL for the first synthetic native profile.

This is a deliberately small parser, not an Oracle DDL parser or Forms compiler.
It performs no I/O, executes no SQL, and never infers a key from a Forms item.
READY means the supplied text fits ``native-table-form-v1`` only; it does not
prove live-schema identity, business equivalence, deployment or runtime tests.

Accepted DDL is exactly one CREATE TABLE with an unquoted FOX_NATIVE_ name,
2..20 NUMBER, DATE or VARCHAR2(n) columns, optional NULL/NOT NULL, and exactly
one inline NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY.
No default expressions, precision, length semantics, table constraints, storage
clauses, scripts, data records or further statements are accepted. SQL comments
and harmless whitespace are allowed. Names are normalized only after proving
that they are unquoted identifiers. Existing source intake is still mandatory.
"""
from __future__ import annotations

import hashlib
import re
import unicodedata
from pathlib import PurePosixPath

from defusedxml import ElementTree as ET

from .intake import MAX_CONVERSION_BYTES, SECRETS


PROFILE_ID = "native-table-form-v1"
DATA_MODE = "synthetic_test_only"
_IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9_]{0,29}\Z")
_EXCLUDED = frozenset(
    "ACCESS ADD ALL ALTER AND ANY AS ASC AUDIT BETWEEN BY CHAR CHECK CLUSTER "
    "COLUMN COMMENT COMPRESS CONNECT CREATE CURRENT DATE DECIMAL DEFAULT DELETE "
    "DESC DISTINCT DROP ELSE EXCLUSIVE EXISTS FILE FLOAT FOR FROM GRANT GROUP "
    "HAVING IDENTIFIED IMMEDIATE IN INCREMENT INDEX INITIAL INSERT INTEGER "
    "INTERSECT INTO IS LEVEL LIKE LOCK LONG MAXEXTENTS MINUS MLSLABEL MODE "
    "MODIFY NOAUDIT NOCOMPRESS NOT NOWAIT NULL NUMBER OF OFFLINE ON ONLINE "
    "OPTION OR ORDER PCTFREE PRIOR PRIVILEGES PUBLIC RAW RENAME RESOURCE REVOKE "
    "ROW ROWID ROWNUM ROWS SELECT SESSION SET SHARE SIZE SMALLINT START "
    "SUCCESSFUL SYNONYM SYSDATE TABLE THEN TO TRIGGER UID UNION UNIQUE UPDATE "
    "USER VALIDATE VALUES VARCHAR VARCHAR2 VIEW WHENEVER WHERE WITH "
    "PRIMARY KEY IDENTITY CONSTRAINT".split()
)
_LABEL_SQL = re.compile(
    r"\b(?:SELECT\b.+\bFROM|INSERT\s+INTO|UPDATE\b.+\bSET|DELETE\s+FROM|"
    r"(?:CREATE|ALTER|DROP)\s+(?:TABLE|VIEW|PROCEDURE|FUNCTION|USER|INDEX)|"
    r"EXECUTE\s+IMMEDIATE|BEGIN\b.+\bEND)\b", re.I,
)
_COLUMN = re.compile(
    r"(?P<name>[A-Za-z][A-Za-z0-9_]{0,29})\s+"
    r"(?P<type>NUMBER|DATE|VARCHAR2\s*\(\s*(?P<length>[0-9]{1,4})\s*\))"
    r"(?P<tail>(?:\s+[A-Za-z]+)*)\s*\Z", re.I,
)
_IDENTITY = re.compile(
    r"GENERATED BY DEFAULT ON NULL AS IDENTITY(?: NOT NULL)? PRIMARY KEY\Z",
)
_BLOCKING_OBJECTS = {
    "menumodule": "Menu modules require their own reviewed navigation mapping.",
    "objectlibrary": "Object-library inheritance requires a separately reviewed mapping.",
    "librarymodule": "Library modules require a separately reviewed business-code mapping.",
    "attachedlibrary": "Attached library behavior requires a separate reviewed mapping.",
    "reportobject": "Reports are not converted by the native table-form profile.",
    "recordgroup": "Record-group queries need an explicit reviewed LOV/dependency mapping.",
    "lov": "LOVs need an explicit reviewed lookup mapping.",
    "relation": "Master/detail relations are outside the single-table profile.",
}
_CODE_ATTRIBUTES = {"triggertext", "programunittext", "plsqlcode", "code", "querytext"}


class _Unsupported(ValueError):
    def __init__(self, code, message):
        self.code = code
        super().__init__(message)


def _identifier(value):
    if not isinstance(value, str) or not _IDENTIFIER.fullmatch(value):
        raise _Unsupported("UNSUPPORTED_IDENTIFIER", "Use unquoted, unqualified identifiers of at most 30 ASCII characters; schema names are not inferred.")
    value = value.upper()
    if value in _EXCLUDED:
        raise _Unsupported("UNSUPPORTED_IDENTIFIER", "An identifier is excluded by the native profile.")
    return value


def _label(value):
    if not 1 <= len(value) <= 80 or not value.strip():
        return False
    if any(unicodedata.category(c).startswith("C") or unicodedata.category(c) in ("Zl", "Zp") for c in value):
        return False
    return not any(t in value for t in ("<", ">", "`", ";", "--", "/*", "*/", "{", "}")) and not _LABEL_SQL.search(value)


def _humanize(name):
    return " ".join(part if part in {"ID", "URL", "API"} else part.capitalize() for part in name.split("_"))


def _strip_comments(text):
    """Replace comments with whitespace, without joining SQL identifier tokens.

    Quoted text remains visible so comments in a literal cannot hide a trailing
    statement. Unterminated/nested comments and unterminated quotes fail closed.
    """
    pieces, pos = [], 0
    while pos < len(text):
        if text.startswith("--", pos):
            end = text.find("\n", pos + 2)
            end = len(text) if end < 0 else end
            pieces.append(" ")
            pos = end
        elif text.startswith("/*", pos):
            end = text.find("*/", pos + 2)
            if end < 0 or "/*" in text[pos + 2:end]:
                raise _Unsupported("UNPARSED_DDL", "Unterminated or nested SQL comments are not supported.")
            pieces.append(" ")
            pos = end + 2
        elif text[pos] in "'\"":
            quote, end = text[pos], pos + 1
            while end < len(text):
                if text[end] == quote:
                    if end + 1 < len(text) and text[end + 1] == quote:
                        end += 2
                        continue
                    break
                end += 1
            if end == len(text):
                raise _Unsupported("UNPARSED_DDL", "Unterminated SQL quoted text is not supported.")
            pieces.append(text[pos:end + 1])
            pos = end + 1
        else:
            pieces.append(text[pos])
            pos += 1
    return "".join(pieces)


def _parse_ddl(text, *, allow_original_table=False):
    """Parse the complete grammar; only the project planner opts out of prefix admission.

    This flag changes no column/key/constraint grammar and performs no mapping.
    An original-name result is source evidence, not a renderable physical spec.
    """
    clean = _strip_comments(text).strip()
    if re.search(r"\b(?:INSERT|MERGE)\s+INTO\b|\b(?:UPDATE|DELETE)\b", clean, re.I):
        raise _Unsupported("DATA_OR_SCRIPT_SQL", "Data-loading/DML statements are not accepted as schema evidence; supply structure without records or executable scripts.")
    if "'" in clean or '"' in clean:
        raise _Unsupported("UNPARSED_DDL", "Quoted identifiers, literals and default expressions are outside the native DDL subset.")
    match = re.fullmatch(r"CREATE\s+TABLE\s+([^\s(]+)\s*\((.*)\)\s*;?", clean, re.I | re.S)
    if not match:
        raise _Unsupported("UNPARSED_DDL", "Supply exactly one complete CREATE TABLE statement; additional statements, scripts and unparsed clauses are blocked.")
    table = _identifier(match[1])
    if not allow_original_table and not table.startswith("FOX_NATIVE_"):
        raise _Unsupported("NON_SYNTHETIC_TABLE", "This profile only accepts explicit FOX_NATIVE_ synthetic tables; customer table names are never renamed automatically.")
    declarations = match[2].split(",")
    if not 2 <= len(declarations) <= 20:
        raise _Unsupported("COLUMN_COUNT", "The native profile requires 2 to 20 columns.")
    columns, names = [], set()
    for declaration in declarations:
        if re.match(r"\s*(?:CONSTRAINT|PRIMARY|FOREIGN|UNIQUE|CHECK)\b", declaration, re.I):
            raise _Unsupported("TABLE_CONSTRAINT_UNSUPPORTED", "Table-level/composite keys, checks and foreign keys require a wider explicit profile; no constraint is discarded.")
        column_match = _COLUMN.fullmatch(declaration.strip())
        if not column_match:
            raise _Unsupported("UNPARSED_DDL", "A column contains unsupported or unparsed DDL; only NUMBER, DATE and VARCHAR2(n) with explicit supported nullability/key clauses are accepted.")
        name = _identifier(column_match["name"])
        if name in names:
            raise _Unsupported("DUPLICATE_COLUMN", "Column names must be unique.")
        names.add(name)
        dtype = "VARCHAR2" if column_match["length"] is not None else column_match["type"].upper()
        tail = " ".join(column_match["tail"].upper().split())
        identity = bool(_IDENTITY.fullmatch(tail))
        if tail not in ("", "NULL", "NOT NULL") and not identity:
            raise _Unsupported("UNSUPPORTED_COLUMN_CLAUSE", "A key/default/constraint clause is unsupported; require NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY. Other identity modes are not silently rewritten.")
        if identity and dtype != "NUMBER":
            raise _Unsupported("UNSUPPORTED_KEY", "The single identity primary key must be NUMBER.")
        column = {"name": name, "data_type": dtype, "nullable": not identity and tail != "NOT NULL",
                  "label": _humanize(name), "primary_key": identity, "identity": identity}
        if dtype == "VARCHAR2":
            length = int(column_match["length"])
            if not 1 <= length <= 4000:
                raise _Unsupported("VARCHAR2_LENGTH", "VARCHAR2 length must be between 1 and 4000.")
            column["length"] = length
        columns.append(column)
    if sum(c["primary_key"] for c in columns) != 1:
        raise _Unsupported("EXPLICIT_KEY_REQUIRED", "Supply exactly one inline NUMBER identity primary key; Forms items do not prove a row key.")
    return {"profile_id": PROFILE_ID, "data_mode": DATA_MODE, "table_name": table,
            "columns": columns, "supported_operations": ["query", "insert", "update"]}


def _tag(element):
    return element.tag.rsplit("}", 1)[-1].lower()


def _attrs(element):
    return {key.rsplit("}", 1)[-1].lower(): value for key, value in element.attrib.items()}


def assess_native_source(files: list[dict]) -> dict:
    """Return a bounded typed candidate plus actionable blockers and provenance.

    Entries use FOX's existing intake shape: ``name`` and readable UTF-8 ``text``
    are required. Any READY candidate still requires source approval, schema
    provisioning/verification, independent review and all conversion gates.
    A candidate can be present while BLOCKED; callers must check ``state``.
    """
    return _assess_native_source(files, allow_original_table=False)


def _assess_native_source(files: list[dict], *, allow_original_table=False) -> dict:
    """Shared exact source checks; project-only original-name admission is explicit."""
    blockers, unsupported, refs, forms, tables = [], [], [], [], []
    result = {"state": "BLOCKED", "profile_id": PROFILE_ID, "native_form": None,
              "blockers": blockers, "unsupported": unsupported, "source_refs": refs,
              "scope_note": "Supplied synthetic metadata only. READY is not proof of live schema, business behavior, customer compatibility or an importable package."}

    def block(code, message, source=None, evidence=None, is_unsupported=True):
        item = {"code": code, "message": message}
        if source is not None:
            item["source"] = source
        if evidence is not None:
            item["evidence"] = evidence
        blockers.append(item)
        if is_unsupported:
            unsupported.append({**item, "status": "UNCONVERTED_REVIEW_REQUIRED"})

    if not isinstance(files, list) or not files:
        block("SOURCE_REQUIRED", "Upload one readable Forms module and its supplied CREATE TABLE DDL.", is_unsupported=False)
        return result
    names, total_bytes = set(), 0
    for file in files:
        if not isinstance(file, dict) or not isinstance(file.get("name"), str) or not isinstance(file.get("text"), str):
            block("INVALID_SOURCE", "Each source requires a simple filename and readable UTF-8 text.")
            continue
        name, text = file["name"], file["text"]
        if not name or len(name) > 180 or any(c in name for c in ("/", "\\", ":", "..")) or any(ord(c) < 32 for c in name):
            block("UNSAFE_SOURCE_NAME", "Use simple source filenames without path components.")
            continue
        if name.casefold() in names:
            block("DUPLICATE_SOURCE", "Source filenames must be unique, including case.", name)
            continue
        names.add(name.casefold())
        try:
            raw = text.encode("utf-8")
        except UnicodeEncodeError:
            block("INVALID_SOURCE", "Source contains invalid Unicode text.", name)
            continue
        total_bytes += len(raw)
        if not raw or "\0" in text or len(raw) > MAX_CONVERSION_BYTES:
            block("INVALID_SOURCE", "Use nonempty, bounded readable source text without binary bytes.", name)
            continue
        refs.append({"source": name, "kind": "source_file", "text_sha256": hashlib.sha256(raw).hexdigest()})
        if any(re.search(pattern, text) for pattern in SECRETS):
            block("SENSITIVE_SOURCE", "Possible credential or personal identifier detected; redact locally before processing.", name)
            continue
        suffix = PurePosixPath(name).suffix.lower()
        if suffix == ".sql":
            try:
                spec = _parse_ddl(text, allow_original_table=allow_original_table)
                tables.append((name, spec))
                refs.append({"source": name, "kind": "table_definition", "target": spec["table_name"], "evidence": "complete CREATE TABLE subset"})
            except _Unsupported as exc:
                block(exc.code, str(exc), name)
        elif suffix == ".xml":
            try:
                root = ET.fromstring(text, forbid_dtd=True, forbid_entities=True, forbid_external=True)
            except Exception:
                block("INVALID_FORMS_XML", "Malformed XML, DTDs and entities are not accepted; export readable Forms XML locally.", name)
                continue
            modules = [root] if _tag(root) == "formmodule" else [e for e in root if _tag(e) == "formmodule"] if _tag(root) == "module" else []
            if not modules:
                block("NO_FORM_MODULE", "This file has no supported FormModule; menus, libraries and unrelated XML need a separately reviewed mapping.", name)
            for module in modules:
                if not _attrs(module).get("name", "").strip():
                    block("UNNAMED_FORM_MODULE", "The Forms module must have an explicit name.", name)
                forms.append((name, module))
            for element in root.iter():
                tag, attrs = _tag(element), _attrs(element)
                if tag == "formmodule" and element not in modules:
                    block("FORM_SELECTION_REQUIRED", "Nested Forms modules are ambiguous and are not merged automatically.", name)
                code = any(value.strip() for key, value in attrs.items() if key in _CODE_ATTRIBUTES)
                code = code or (tag in {"trigger", "programunit"} and bool("".join(element.itertext()).strip()))
                if code:
                    block("BUSINESS_CODE_REVIEW_REQUIRED", "Forms/PLSQL source code is retained as unconverted behavior, not treated as table records or automatically translated; approve an explicit mapping before conversion.", name, f"{tag}:{attrs.get('name', 'unnamed')}")
                if tag in _BLOCKING_OBJECTS:
                    block("UNSUPPORTED_FORMS_OBJECT", _BLOCKING_OBJECTS[tag], name, f"{tag}:{attrs.get('name', 'unnamed')}")
        else:
            block("UNSUPPORTED_SOURCE_KIND", "Only a readable Forms .xml and one structure-only .sql file are supported by this native profile; supporting source must not be silently omitted.", name)
    if total_bytes > MAX_CONVERSION_BYTES:
        block("SOURCE_SIZE_LIMIT", "The native source package exceeds the 300 KB conversion limit.")
    if len(forms) != 1:
        block("FORM_SELECTION_REQUIRED", "Supply exactly one named Forms module; multiple modules are not selected or merged automatically.", is_unsupported=False)
    if len(tables) != 1:
        block("DDL_REQUIRED" if not tables else "DDL_SELECTION_REQUIRED", "Supply exactly one supported CREATE TABLE definition matching the selected Forms block; no row key or schema is guessed.", is_unsupported=False)
    if len(forms) != 1 or len(tables) != 1:
        return result
    name, module = forms[0]
    blocks = [e for e in module.iter() if _tag(e) == "block"]
    if len(blocks) != 1:
        block("BLOCK_SELECTION_REQUIRED", "This profile requires exactly one table-backed Forms block; additional table/control blocks require an explicit wider mapping.", name)
        return result
    attrs = _attrs(blocks[0])
    try:
        table = _identifier(attrs.get("querydatasourcename", "").strip())
    except _Unsupported as exc:
        block(exc.code, "Block.QueryDataSourceName must name one unqualified table; query sources and missing/schema-qualified names are not inferred.", name, "Block.QueryDataSourceName")
        return result
    refs.append({"source": name, "kind": "forms_table", "module": _attrs(module).get("name"), "block": attrs.get("name"), "target": table, "evidence": "Block.QueryDataSourceName"})
    if attrs.get("querydatasourcetype", "Table").strip().lower() != "table":
        block("UNSUPPORTED_QUERY_SOURCE", "Only a table query source is supported; views, procedures and query expressions need explicit mapping.", name)
    for key in ("whereclause", "orderbyclause", "dmlreturnvalue", "precomputedquery"):
        if attrs.get(key, "").strip():
            block("BLOCK_BEHAVIOR_REVIEW_REQUIRED", "Source filters, ordering and custom DML behavior require explicit mapping; no clause is silently discarded.", name, f"Block.{key}")
    for key in ("insertallowed", "updateallowed", "queryallowed"):
        if attrs.get(key, "true").strip().lower() not in {"true", "yes"}:
            block("BLOCK_BEHAVIOR_REVIEW_REQUIRED", "The source restricts an operation that this profile exposes; review the supported operation mapping.", name, f"Block.{key}")
    spec = tables[0][1]
    if table != spec["table_name"]:
        block("TABLE_MISMATCH", "The supplied CREATE TABLE does not match Block.QueryDataSourceName; do not guess or rename the target.", name, "Block.QueryDataSourceName")
        return result
    result["native_form"] = spec
    columns = {column["name"]: column for column in spec["columns"]}
    prompts: dict[str, set[str]] = {}
    mapped_columns = set()
    for item in blocks[0].iter():
        if _tag(item) not in {"item", "formitem"}:
            continue
        item_attrs = _attrs(item)
        if item_attrs.get("databaseitem", "true").strip().lower() not in {"true", "yes"}:
            block("CONTROL_ITEM_REVIEW_REQUIRED", "Non-database Forms items need an explicit UI behavior mapping.", name, item_attrs.get("name", "unnamed"))
            continue
        try:
            column = _identifier(item_attrs.get("columnname") or item_attrs.get("name", ""))
        except _Unsupported:
            block("ITEM_MAPPING_REQUIRED", "An item cannot be mapped to an explicit DDL column.", name, "Item.ColumnName/Name")
            continue
        if column not in columns:
            block("ITEM_COLUMN_MISSING", "A Forms item references a column absent from the supplied DDL.", name, column)
            continue
        mapped_columns.add(column)
        if item_attrs.get("itemtype", "Text Item").strip().lower().replace(" ", "") != "textitem":
            block("ITEM_BEHAVIOR_REVIEW_REQUIRED", "Only plain text-backed database items are mapped by this profile; other item types need a reviewed mapping.", name, column)
        if not columns[column]["primary_key"]:
            for key in ("visible", "enabled", "insertallowed", "updateallowed", "queryallowed"):
                if item_attrs.get(key, "true").strip().lower() not in {"true", "yes"}:
                    block("ITEM_BEHAVIOR_REVIEW_REQUIRED", "Hidden, disabled or restricted fields must not silently become editable.", name, f"{column}.{key}")
            if item_attrs.get("queryonly", "false").strip().lower() not in {"false", "no"}:
                block("ITEM_BEHAVIOR_REVIEW_REQUIRED", "A query-only Forms field requires an explicit read-only mapping.", name, column)
        for key in ("lovname", "initialvalue", "formatmask", "calculationmode", "formula"):
            value = item_attrs.get(key, "").strip()
            if value and not (key == "calculationmode" and value.lower() == "none"):
                block("ITEM_BEHAVIOR_REVIEW_REQUIRED", "LOVs, defaults, calculations and format masks require a reviewed native mapping.", name, f"{column}.{key}")
        if item_attrs.get("required", "false").strip().lower() in {"true", "yes"} and columns[column]["nullable"]:
            block("ITEM_BEHAVIOR_REVIEW_REQUIRED", "The Forms item is required but the supplied DDL is nullable; decide the business validation explicitly.", name, column)
        prompt = item_attrs.get("prompt", "").strip()
        if prompt:
            if not _label(prompt):
                block("UNSAFE_ITEM_PROMPT", "A label is not bounded plain text; review it before generation.", name, column)
                continue
            prompts.setdefault(column, set()).add(prompt)
    for column in columns.values():
        if not column["primary_key"] and column["name"] not in mapped_columns:
            block("COLUMN_ITEM_MAPPING_REQUIRED", "A non-key DDL column has no mapped Forms item; do not expose additional schema fields automatically.", name, column["name"])
    for column, values in prompts.items():
        if len(values) != 1:
            block("AMBIGUOUS_ITEM_PROMPT", "Multiple different prompts map to the same column; choose one explicitly.", name, column)
        else:
            columns[column]["label"] = next(iter(values))
            refs.append({"source": name, "kind": "column_label", "target": column, "evidence": "Item.Prompt"})
    for column in columns.values():
        if not _label(column["label"]):
            block("LABEL_REVIEW_REQUIRED", "The derived label is outside the native plain-text contract; provide a reviewed Forms prompt.", name, column["name"])
    if not blockers:
        result["state"] = "READY"
    return result
